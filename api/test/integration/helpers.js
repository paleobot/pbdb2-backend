import { randomBytes } from 'node:crypto';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import dotenv from 'dotenv';
import pg from 'pg';

import { loadPgConfig } from '../../src/config.js';

const { Client, Pool } = pg;
const __dirname = dirname(fileURLToPath(import.meta.url));

// The backend root's `.env`, found from this file, not the working directory.
dotenv.config({ path: join(__dirname, '../../../.env'), quiet: true });

// The backend schema (with its lineage triggers) lives in db/ at the backend
// repository root as NN-*.sql files (01-dictionaries, 02-core, 03-taxa),
// applied in sorted name order. DDL_DIR overrides it.
const DEFAULT_DDL_DIR = join(__dirname, '../../../db');

function sslFrom(config) {
  return config.caCertPath ? { ca: readFileSync(config.caCertPath) } : false;
}

/**
 * Provision an ephemeral test database against the PostgreSQL identified by
 * `PG_*`, load the backend DDL into it (triggers and all), and return a pool
 * plus a `teardown` that drops it.
 *
 * Returns `{ available: false, reason }` — never throws — when there is no
 * connection or the schema files are missing, so integration tests SKIP cleanly
 * rather than failing on machines without a database.
 */
export async function setupTestDb() {
  const config = loadPgConfig();
  if (!config.configured) {
    return {
      available: false,
      reason: `PG_* not set (missing ${config.missing.join(', ')}); skipping integration tests`,
    };
  }

  const ddlDir = process.env.DDL_DIR || DEFAULT_DDL_DIR;
  const ddlFiles = existsSync(ddlDir)
    ? readdirSync(ddlDir).filter((f) => /^\d\d-.*\.sql$/.test(f)).sort()
    : [];
  if (ddlFiles.length === 0) {
    return { available: false, reason: `no NN-*.sql DDL files in ${ddlDir}; set DDL_DIR` };
  }

  const ssl = sslFrom(config);
  const adminCfg = {
    host: config.host,
    port: config.port,
    user: config.user,
    password: config.password,
    database: config.database,
    ssl,
  };

  const admin = new Client(adminCfg);
  try {
    await admin.connect();
  } catch (err) {
    return { available: false, reason: `cannot reach PostgreSQL: ${err.message}; skipping` };
  }

  const dbName = `pbdb2_test_${randomBytes(6).toString('hex')}`;
  await admin.query(`CREATE DATABASE "${dbName}"`);
  await admin.end();

  async function dropDatabase() {
    const dropper = new Client(adminCfg);
    await dropper.connect();
    // Drop fails if any session is still attached; close stragglers first.
    await dropper.query(
      `SELECT pg_terminate_backend(pid) FROM pg_stat_activity
        WHERE datname = $1 AND pid <> pg_backend_pid()`,
      [dbName],
    );
    await dropper.query(`DROP DATABASE IF EXISTS "${dbName}"`);
    await dropper.end();
  }

  // From here on the database exists, so any failure must drop it rather than
  // leak an orphan (e.g. a broken DDL file failing to load).
  const pool = new Pool({ ...adminCfg, database: dbName });
  try {
    await pool.query(ddlFiles.map((f) => readFileSync(join(ddlDir, f), 'utf8')).join('\n'));
  } catch (err) {
    await pool.end().catch(() => {});
    await dropDatabase().catch(() => {});
    return { available: false, reason: `failed to load the DDL in ${ddlDir}: ${err.message}; skipping` };
  }

  async function teardown() {
    await pool.end();
    await dropDatabase();
  }

  return { available: true, pool, dbName, teardown };
}

/**
 * Mint `n` permids under `prefix` (`REF`, `PRS`, `COL`, …) through the database's
 * own `mint_permids()`. That function is the only implementation of the permid
 * format (openspec/specs/prefixed-permids): it takes numbers from the prefix's
 * sequence, registers them in `permids` (which every permid column references),
 * and returns them in increasing numeric order, so fixtures minted in turn list
 * in mint order.
 *
 * @returns {Promise<string[]>}
 */
export async function mintPermids(pool, prefix, n) {
  const { rows } = await pool.query('SELECT mint_permids($1, $2) AS permids', [prefix, n]);
  return rows[0].permids;
}

/** Mint one permid; see `mintPermids`. */
export async function mintPermid(pool, prefix) {
  return (await mintPermids(pool, prefix, 1))[0];
}

/**
 * Bootstrap a person row. `persons.authorizer_person_id` is NOT NULL and
 * self-referential, so the very first person authorizes itself (explicit id,
 * the column is GENERATED BY DEFAULT so this is allowed). Resource rows below
 * reference this person as both enterer and authorizer.
 *
 * @returns {Promise<number>} the person id
 */
export async function seedPerson(pool) {
  const { rows } = await pool.query(
    `INSERT INTO persons (id, permid, role_id, person, authorizer_person_id)
     VALUES (1, $1, (SELECT id FROM dictionaries.roles WHERE name = 'Superadmin'),
             '{"name":"Seed Admin"}'::jsonb, 1)
     ON CONFLICT (id) DO NOTHING
     RETURNING id`,
    [await mintPermid(pool, 'PRS')],
  );
  return rows.length ? rows[0].id : 1;
}

/**
 * Insert a reference row, returning its serial id. Pass `permid` to extend an
 * existing lineage (the triggers handle succession); omit `removed` for a live
 * row.
 */
export async function insertRef(pool, { permid, personId, reference = {}, removed = null }) {
  const { rows } = await pool.query(
    `INSERT INTO refs (permid, authorizer_person_id, enterer_person_id, reference, removed)
     VALUES ($1, $2, $2, $3::jsonb, $4)
     RETURNING id, permid`,
    [permid, personId, JSON.stringify(reference), removed],
  );
  return rows[0];
}

