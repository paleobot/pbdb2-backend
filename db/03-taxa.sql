CREATE EXTENSION IF NOT EXISTS ltree;

-- ============================================================================
-- LAYER 2 — THE LINNAEAN DERIVATION
-- ----------------------------------------------------------------------------
-- derive_linnaean(permids) is a pure function over Layer 1 (the opinion ledgers,
-- in 02-core.sql) and the single
-- definition of truth for the Linnaean hierarchy (§9.5.2, §9.8): two
-- union-finds (lineage over 'name' edges → name-lineages ≈ orig_no; concept
-- over 'concept' edges → concepts ≈ synonym_no), an ordered ranking for the
-- accepted spelling per lineage, and the winning assignment pooled across the
-- whole concept. Called by both the hot path (B2 statement trigger over
-- dependency_closure) and the cold path (rebuild_linnaean() / migration / CI),
-- which makes the invariant derive_linnaean(all) ≡ {the current taxa_linnaean
-- rows} checkable (assert_linnaean_invariant()).
--
-- taxa_linnaean/derive_linnaean() is one of several derivations sharing this
-- opinion-table input: taxa_clades/derive_taxa_clades() covers the clade-to-
-- clade hierarchy this derivation excludes, taxa_attachments/
-- derive_clade_attachments() covers the cross-boundary edges neither covers,
-- and taxa/derive_taxa() (defined later in this file) is the primary,
-- combined derivation over all of it at once — see
-- openspec/changes/taxa-tables-rework/{proposal,design}.md.
--
-- The functions are DEFINED after the taxa_linnaean ledger below (they reference
-- it and every opinion table). See the "LAYER 2 — THE LINNAEAN DERIVATION
-- (derive_linnaean / rebuild_linnaean / assert_linnaean_invariant)" block after
-- it.
-- ============================================================================


-- ============================================================================
-- LAYER 3 — THE LINNAEAN LEDGER (materialized output of derive_linnaean())
-- ----------------------------------------------------------------------------
-- Secondary as of the taxa-tables-rework change: the primary, caller-facing
-- ledger is now `taxa` (the combined Linnaean+clade derivation, defined later
-- in this file) — `taxa_linnaean` remains as a supporting table and as
-- input to `taxa_clades`/`derive_taxa_clades()` and
-- `taxa_attachments`/`derive_clade_attachments()`, both of which read it
-- directly. See openspec/changes/taxa-tables-rework/{proposal,design}.md.
-- ============================================================================

-- Pure materialized output — nothing here is hand-entered, hence no authorizer /
-- enterer (attributing a derived row to a person would be a lie). ONE ROW PER
-- PERMID = per name-as-spelled (§9.8), 1:1 with Classic's taxa_tree_cache. Must be
-- losslessly rebuildable by derive(); anything derive() cannot reconstruct belongs
-- in "OUTSIDE THE STACK" (02-core.sql), not here.
CREATE TABLE taxa_linnaean (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permid uuid NOT NULL CHECK ((get_byte(uuid_send(permid), 6) >> 4) = 7),  -- this name-as-spelled; replaces legacy taxon_no (NOT orig_no)

    -- IMMUTABLE identity, denormalized from this permid's minting name_opinion.
    -- Never changes on re-derivation: a respelling/rank change is a DIFFERENT permid.
    name text NOT NULL,
    -- NOT NULL (§10.6 D11): every permid is denormalized from its minting name_opinion,
    -- whose rank_id the D9 shape CHECK forces non-NULL ('unranked' is itself a rank).
    -- Doubles as a tripwire — derive() materializing a permid with no minting opinion
    -- fails loudly here instead of emitting a rankless taxon.
    rank_id integer REFERENCES dictionaries.taxonomy_ranks("id") NOT NULL,
    authority_id bigint REFERENCES authorities("id"),

    -- The derived identity triad. All three are permid pointers, not SQL foreign
    -- keys; members of a grouping share equal values:
    --   original_permid          groups the name-lineage                ≈ orig_no
    --   accepted_spelling_permid the accepted spelling of THIS lineage  ≈ spelling_no
    --   concept_permid           the accepted spelling of the SENIOR synonym ≈ synonym_no
    -- These three equalities replace the old `accepted` boolean's jobs (§10.4).
    original_permid uuid NOT NULL,
    accepted_spelling_permid uuid NOT NULL,
    concept_permid uuid NOT NULL,

    -- Classification. Adjacency (containing_concept_permid) is PRIMARY;
    -- classification_path is an explicitly derived materialization that can be
    -- reshaped or dropped as a cache change (§9.7.4). Path-primary would be the
    -- nested-set trap again.
    containing_concept_permid uuid,        -- NULL = root
    classification_path ltree,             -- ltree of concept permids, root → node

    -- Nomenclatural validity: NULL = valid. Replaces the old `accepted` boolean's
    -- second job, as an enum not a boolean ("invalid" and "is a junior synonym" are
    -- independent conditions).
    nomenclatural_status_id integer REFERENCES dictionaries.nomenclatural_statuses("id"),

    -- Provenance: which opinion won each dimension (§7 auditability). No
    -- winning_rank_opinion_id — rank came from winning_name_opinion (§9.8).
    winning_name_opinion_id       bigint REFERENCES name_opinions("id"),
    winning_assignment_opinion_id bigint REFERENCES assignment_opinions("id"),
    winning_validity_opinion_id   bigint REFERENCES validity_opinions("id"),

    removed boolean,
    created_at timestamptz DEFAULT NOW(),

    UNIQUE (permid)
);

-- NOT versioned (no preceded_by_id/succeeded_by_id, no
-- install_version_triggers() call) — a plain cache, one row per permid, upserted in
-- place by rebuild_linnaean(). taxa_linnaean is pure derive() output and fully
-- rebuildable from Layer 1 opinions at any time (the §9.5.5 invariant), so there is
-- no independent history to keep here: the opinions themselves remain the durable,
-- versioned record of what was asserted, when (§10.6 D8, superseded — see
-- docs/classic-taxa-opinions.md). UNIQUE (permid) above is what guarantees "one row
-- per permid" now that there is no head/succession chain to enforce it.

-- These back derive() and the read path; UNIQUE (permid) above already covers
-- exact-permid lookups.
CREATE INDEX taxa_linnaean_original_idx
    ON taxa_linnaean (original_permid);
CREATE INDEX taxa_linnaean_accepted_spelling_idx
    ON taxa_linnaean (accepted_spelling_permid);
CREATE INDEX taxa_linnaean_concept_idx
    ON taxa_linnaean (concept_permid);
CREATE INDEX taxa_linnaean_containing_idx
    ON taxa_linnaean (containing_concept_permid);
CREATE INDEX taxa_linnaean_path_idx
    ON taxa_linnaean USING gist (classification_path);
CREATE INDEX taxa_linnaean_name_idx
    ON taxa_linnaean (name);



-- ============================================================================
-- LAYER 2 — THE LINNAEAN DERIVATION  (derive_linnaean / rebuild_linnaean /
-- assert_linnaean_invariant)
-- ----------------------------------------------------------------------------
-- Pure derivation of the taxa_linnaean ledger from the Layer 1 opinion tables.
-- In public with descriptive names (no dedicated schema), matching the
-- versioning-function convention. See docs/classic-taxa-opinions.md §9.5.2 /
-- §9.8.4 and openspec/changes/taxa-opinion-derivation/design.md.
--
-- classification_path is an ltree of concept permids with hyphens replaced by
-- underscores (ltree labels forbid '-').
--
-- The primary, combined derivation (`taxa`/`derive_taxa()`) is defined later in
-- this file, after `taxa_clades` and `taxa_attachments` — see
-- openspec/changes/taxa-tables-rework/{proposal,design}.md.
-- ============================================================================

-- ============================================================================
-- cycle_cuts — permanent audit log of cuts made by derive_linnaean()'s,
-- derive_taxa_clades()'s, and derive_taxa()'s classification cycle-breaking
-- loops
-- ============================================================================
-- derive_linnaean()/derive_taxa_clades()/derive_taxa() are pure functions --
-- calling them directly (e.g. for exploration) must not have side effects, so
-- they never write here themselves. Only the cold-path
-- rebuild_linnaean()/rebuild_taxa_clades()/rebuild_taxa() do, immediately after
-- calling derive_*(NULL): each derive_*() call leaves its own
-- _dt_excluded_opinions/_dtc_excluded_opinions/_dtu_excluded_opinions temp
-- table behind for the rest of the session, and rebuild_*() reads it from
-- there. Truncated (per source) and repopulated on every rebuild, same as
-- taxa_linnaean/taxa_clades/taxa themselves -- this is a snapshot of the
-- CURRENT cut set, not a historical log; a cut that no longer recurs (opinion
-- data changed) simply stops appearing on the next rebuild.
CREATE TABLE cycle_cuts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL CHECK (source IN ('taxa', 'taxa_linnaean', 'taxa_clades')),
    concept_permid uuid,
    cut_opinion_id bigint NOT NULL REFERENCES assignment_opinions("id"),
    cycle_members uuid[] NOT NULL,
    created_at timestamptz DEFAULT NOW()
);

-- optimize-derive-taxa-seed: `seed IS NOT NULL` walks upward from each seed
-- permid's own con_rep instead of running the full algorithm below and
-- filtering at the end -- see derive_taxa()'s own header comment for the
-- full algorithm and correctness argument (identical here, just ported to
-- this function's own table names/rank exclusions). Live profiling found a
-- different cost shape than derive_taxa(): this function's cycle-breaking
-- loop is normally a cheap, mostly-idle safety net (0 cuts against the
-- current dataset) rather than the dominant cost -- the win here instead
-- comes from skipping the bulk _dt_assign/_dt_node build and the full-tree
-- _dt_path build. Typical result: ~26s down to ~13s for a single-permid seed.
CREATE OR REPLACE FUNCTION derive_linnaean(seed uuid[] DEFAULT NULL)
RETURNS TABLE (
    permid uuid,
    name text,
    rank_id integer,
    authority_id bigint,
    original_permid uuid,
    accepted_spelling_permid uuid,
    concept_permid uuid,
    containing_concept_permid uuid,
    classification_path ltree,
    nomenclatural_status_id integer,
    winning_name_opinion_id bigint,
    winning_assignment_opinion_id bigint,
    winning_validity_opinion_id bigint
) LANGUAGE plpgsql AS $fn$
#variable_conflict use_column
DECLARE
    cut_opinion_id bigint;
    iter integer := 0;
    peeled_count integer;
    -- optimize-derive-taxa-cycle-loop: incremental _dt_assign/_dt_node
    -- recompute after the first loop pass (see that change's design.md).
    affected_con_rep uuid;
    new_opinion_id bigint;
    new_containing_permid uuid;
    new_containing_con_rep uuid;
    new_evidence boolean;
    new_yr integer;
    new_is_senior boolean;
    -- optimize-derive-taxa-seed: per-seed upward walk used instead of the
    -- above for seed IS NOT NULL (see that change's design.md, Decision 1,
    -- and Decision 2 for why this applies here too even though live-profiling
    -- found this function's cycle loop itself is cheap already -- the win
    -- here comes from skipping the bulk _dt_assign/_dt_node/_dt_path builds,
    -- not from skipping cycle-loop iterations).
    swalk_con_rep uuid;
    swalk_seed_con_rep uuid;
    swalk_cached boolean;
    swalk_step integer;
    swalk_cycle_start_step integer;
    swalk_cut_opinion_id bigint;
    swalk_iter integer;
    swalk_concept_permid uuid;
    swalk_concept_rank_id integer;
    swalk_new_opinion_id bigint;
    swalk_new_containing_permid uuid;
    swalk_new_containing_con_rep uuid;
    swalk_new_containing_concept_permid uuid;
    swalk_new_evidence boolean;
    swalk_new_yr integer;
    swalk_new_is_senior boolean;
BEGIN
    -- ---- identity: one row per minted permid, from its own root row only ---
    DROP TABLE IF EXISTS _dt_identity;
    CREATE TEMP TABLE _dt_identity AS
    SELECT n.subject_permid AS permid, n.id AS opinion_id, n.new_name, n.rank_id, n.authority_id
    FROM name_opinions n
    WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
      AND n.edge_class = 'root';
    CREATE INDEX ON _dt_identity(permid);
    ANALYZE _dt_identity;

    -- root minting is a one-time act (§9.8.1), not a ranking contest: more than
    -- one live root row for a permid is an integrity violation to raise on, not
    -- a candidate set to silently pick a winner from.
    IF EXISTS (SELECT 1 FROM _dt_identity GROUP BY permid HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'derive_linnaean: permid % has more than one live root row (identity re-minted)',
            (SELECT permid FROM _dt_identity GROUP BY permid HAVING count(*) > 1 LIMIT 1);
    END IF;

    -- ---- candidate introducing edges: one row per (permid, opinion) --------
    -- Both classes that can INTRODUCE a permid: 'root' mints identity (new_name +
    -- rank_id, no target), 'name' asserts this spelling is a form of an earlier one
    -- (target, no identity). A 'root' row is name-shaped too -- it is about a name --
    -- so read the enum as {mint, name-relationship, concept-relationship}, not as
    -- "root vs name": 'root' is kept distinct because it mints rather than relates,
    -- which is why it can never contribute a union-find edge (see _dt_lin_winner).
    DROP TABLE IF EXISTS _dt_edge_cand;
    CREATE TEMP TABLE _dt_edge_cand AS
    SELECT n.subject_permid AS permid, n.id AS opinion_id, n.edge_class, n.target_permid,
           n.evidence,
           COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
           nr.never_accepted, n.negates
    FROM name_opinions n
    JOIN dictionaries.namechange_reasons nr ON nr.id = n.reason_id
    LEFT JOIN refs r ON r.id = n.reference_id
    WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
      AND n.edge_class IN ('root','name');
    CREATE INDEX ON _dt_edge_cand(permid);
    ANALYZE _dt_edge_cand;

    -- each permid's own canonical introducing edge (root or name, whichever
    -- ranks highest) -- feeds eligibility (below), never union-find membership.
    -- Negating rows are excluded from this ranking pool entirely (not merely
    -- filtered afterward): a negation rejects a RELATIONSHIP to something else,
    -- it doesn't introduce or characterize this permid's own identity, so it
    -- must never win "canonical introducing edge" -- if it did, a permid whose
    -- only claim is a successful negation would lose eligibility and its own
    -- (now-singleton) lineage would wrongly exhaust, when it should simply
    -- stand on its own. Every permid's own root row is always a non-negating
    -- candidate, so excluding negating rows here can never itself exhaust a
    -- permid's eligibility.
    --
    -- ranked is marked MATERIALIZED (as are the other non-recursive CTEs
    -- throughout this function) so Postgres plans/executes each stage
    -- independently instead of inlining it into the surrounding query --
    -- CONFIRMED root cause of derive_linnaean() taking 30+ minutes on a full,
    -- real-scale derive-all: with plain (inlined) CTEs, the equivalent of
    -- _dt_linmeta below alone took 6+ minutes; with MATERIALIZED, 3.06s, with
    -- zero logic changes (migration_exploration/testing/test-materialized-
    -- linmeta.js). Missing statistics and union-find data volume were ruled
    -- out first (migration_exploration/testing/diagnose-sink-degeneracy.js,
    -- diagnose-linmeta-pieces.js).
    DROP TABLE IF EXISTS _dt_permid_edge;
    CREATE TEMP TABLE _dt_permid_edge AS
    WITH ranked AS MATERIALIZED (
        SELECT permid, opinion_id, evidence, yr, never_accepted,
               row_number() OVER (PARTITION BY permid
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM _dt_edge_cand
        WHERE negates = false
    )
    SELECT permid, opinion_id, evidence, yr, never_accepted FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dt_permid_edge(permid);
    ANALYZE _dt_permid_edge;

    -- each subject's own top-ranked LINEAGE-class opinion only (root rows have
    -- no target and can never contribute a union-find edge, so _dt_permid_edge
    -- is the wrong source here even though it uses the same ranking). When the
    -- winner negates, target_permid is retained on the row for provenance only
    -- (which relationship this opinion rejects) -- it is never read below;
    -- lin_undir only ever draws edges from non-negating winners.
    DROP TABLE IF EXISTS _dt_lin_winner;
    CREATE TEMP TABLE _dt_lin_winner AS
    WITH ranked AS MATERIALIZED (
        SELECT permid, target_permid, negates,
               row_number() OVER (PARTITION BY permid
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM _dt_edge_cand
        WHERE edge_class = 'name'
    )
    SELECT permid, target_permid, negates FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dt_lin_winner(permid);
    ANALYZE _dt_lin_winner;

    -- ---- lineage union-find (connected components over each subject's own -
    -- winning, non-negating name edge only -- not every current one) ------
    -- (lin_undir is marked MATERIALIZED; reach is the recursive term itself
    -- and can't be inlined regardless, so it's left as-is.)
    DROP TABLE IF EXISTS _dt_lin;
    CREATE TEMP TABLE _dt_lin AS
    WITH RECURSIVE
    lin_undir AS MATERIALIZED (
        SELECT permid AS a, target_permid AS b FROM _dt_lin_winner WHERE negates = false
        UNION
        SELECT target_permid, permid FROM _dt_lin_winner WHERE negates = false
    ),
    reach(src, node) AS (
        SELECT permid, permid FROM _dt_identity
        UNION
        SELECT r.src, u.b FROM reach r JOIN lin_undir u ON u.a = r.node
    )
    SELECT src AS permid, min(node::text)::uuid AS lin_rep FROM reach GROUP BY src;
    CREATE INDEX ON _dt_lin(permid);
    CREATE INDEX ON _dt_lin(lin_rep);
    ANALYZE _dt_lin;

    -- ---- best concept-class opinion targeting each lineage -----------------
    -- Counter-signal for the validity veto below -- see the identical table
    -- in derive_taxa() (fix-nomen-dubium-concept-seniority) for the full
    -- rationale: validity_opinions has no way to positively record that a
    -- later opinion reversed an old invalidating ruling, so a live,
    -- evidenced concept-class opinion deferring to this lineage counts as
    -- proof the name was treated as legitimate afterward.
    DROP TABLE IF EXISTS _dt_concept_target_best;
    CREATE TEMP TABLE _dt_concept_target_best AS
    WITH cand AS MATERIALIZED (
        SELECT lt.lin_rep,
               n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id,
               row_number() OVER (PARTITION BY lt.lin_rep
                   ORDER BY n.evidence DESC,
                            COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                            n.id DESC) AS rn
        FROM name_opinions n
        JOIN _dt_lin lt ON lt.permid = n.target_permid
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
          AND n.edge_class = 'concept' AND n.negates = false
    )
    SELECT lin_rep, evidence, yr, opinion_id FROM cand WHERE rn = 1;
    CREATE INDEX ON _dt_concept_target_best(lin_rep);
    ANALYZE _dt_concept_target_best;

    -- ---- validity per permid (moved up: eligibility below depends on it) ---
    DROP TABLE IF EXISTS _dt_valid;
    CREATE TEMP TABLE _dt_valid AS
    WITH cand AS MATERIALIZED (
        SELECT v.subject_permid AS permid, v.nomenclatural_status_id, v.id AS opinion_id,
               v.evidence,
               COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               ns.invalidates,
               row_number() OVER (PARTITION BY v.subject_permid
                   ORDER BY v.evidence DESC,
                            COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                            v.id DESC) AS rn
        FROM validity_opinions v
        JOIN dictionaries.nomenclatural_statuses ns ON ns.id = v.nomenclatural_status_id
        LEFT JOIN refs r ON r.id = v.reference_id
        WHERE v.removed IS NOT TRUE AND v.succeeded_by_id IS NULL
    )
    SELECT permid, nomenclatural_status_id, opinion_id AS winning_validity_opinion_id,
           evidence, yr, invalidates
    FROM cand WHERE rn = 1;
    CREATE INDEX ON _dt_valid(permid);
    ANALYZE _dt_valid;

    -- ---- validity veto: which permids are actually invalidated -------------
    -- (fix-nomen-dubium-concept-seniority) See the identical, static (not
    -- iterative) determination in derive_taxa() for the full rationale: a
    -- permid whose winning validity opinion has invalidates = true is
    -- excluded only if that opinion's own rating (evidence/yr/id) outranks
    -- the best of its own canonical introducing edge and a live concept-
    -- class opinion naming its lineage as target (_dt_concept_target_best).
    -- Computed once, up front -- never inside a loop reacting to whoever
    -- currently wins a ranking, which (confirmed live) misses exactly the
    -- Triceratops/Agathaumas shape: a non-invalidated candidate winning only
    -- because ITS competitor's disqualifying edge targets an invalidated
    -- lineage that a reactive, winner-only check would never even inspect.
    DROP TABLE IF EXISTS _dt_permid_invalidated;
    CREATE TEMP TABLE _dt_permid_invalidated AS
    SELECT pe.permid
    FROM _dt_permid_edge pe
    JOIN _dt_lin l ON l.permid = pe.permid
    JOIN _dt_valid dv ON dv.permid = pe.permid
    LEFT JOIN _dt_concept_target_best ctb ON ctb.lin_rep = l.lin_rep
    WHERE dv.invalidates = true
      AND (dv.evidence, COALESCE(dv.yr, -999999), dv.winning_validity_opinion_id)
          > (pe.evidence, COALESCE(pe.yr, -999999), pe.opinion_id)
      AND (dv.evidence, COALESCE(dv.yr, -999999), dv.winning_validity_opinion_id)
          > (COALESCE(ctb.evidence, false), COALESCE(ctb.yr, -999999), COALESCE(ctb.opinion_id, -1));
    CREATE INDEX ON _dt_permid_invalidated(permid);
    ANALYZE _dt_permid_invalidated;

    DROP TABLE IF EXISTS _dt_lin_all_invalidated;
    CREATE TEMP TABLE _dt_lin_all_invalidated AS
    SELECT l.lin_rep
    FROM _dt_lin l
    JOIN _dt_permid_edge pe ON pe.permid = l.permid
    WHERE pe.never_accepted = false
    GROUP BY l.lin_rep
    HAVING bool_and(EXISTS (SELECT 1 FROM _dt_permid_invalidated pi WHERE pi.permid = l.permid));
    CREATE INDEX ON _dt_lin_all_invalidated(lin_rep);
    ANALYZE _dt_lin_all_invalidated;

    -- ---- per-lineage: eligibility, topological original_permid, accepted --
    -- spelling ----------------------------------------------------------------
    -- CONFIRMED: this statement alone took 6+ minutes with plain (inlined)
    -- CTEs and 3.06s with all five marked MATERIALIZED, with zero query-logic
    -- changes (migration_exploration/testing/test-materialized-linmeta.js).
    DROP TABLE IF EXISTS _dt_linmeta;
    CREATE TEMP TABLE _dt_linmeta AS
    WITH
    eligible AS MATERIALIZED (
        SELECT pe.permid, pe.evidence, pe.yr, pe.opinion_id
        FROM _dt_permid_edge pe
        JOIN _dt_lin l ON l.permid = pe.permid
        WHERE pe.never_accepted = false
          AND (
            NOT EXISTS (SELECT 1 FROM _dt_permid_invalidated pi WHERE pi.permid = pe.permid)
            OR EXISTS (SELECT 1 FROM _dt_lin_all_invalidated ai WHERE ai.lin_rep = l.lin_rep)
          )
    ),
    sinks AS MATERIALIZED (
        SELECT l.lin_rep, l.permid
        FROM _dt_lin l
        WHERE NOT EXISTS (
            SELECT 1 FROM _dt_lin_winner w
            WHERE w.negates = false AND w.permid = l.permid
        )
    ),
    sink_counts AS MATERIALIZED (
        SELECT lin_rep, count(*) AS n FROM sinks GROUP BY lin_rep
    ),
    roots AS MATERIALIZED (
        SELECT sc.lin_rep, s.permid AS original_permid
        FROM sink_counts sc JOIN sinks s ON s.lin_rep = sc.lin_rep
        WHERE sc.n = 1
        UNION ALL
        SELECT sc.lin_rep,
               (array_agg(cand.permid ORDER BY cand.evidence DESC, cand.yr DESC NULLS LAST,
                          cand.opinion_id DESC, cand.permid))[1]
        FROM sink_counts sc
        JOIN LATERAL (
            SELECT pe.permid, pe.evidence, pe.yr, pe.opinion_id
            FROM (SELECT permid FROM sinks WHERE lin_rep = sc.lin_rep
                  UNION ALL
                  SELECT l.permid FROM _dt_lin l WHERE l.lin_rep = sc.lin_rep AND sc.n = 0) c
            JOIN _dt_permid_edge pe ON pe.permid = c.permid
        ) cand ON true
        WHERE sc.n != 1
        GROUP BY sc.lin_rep
    ),
    spelling AS MATERIALIZED (
        SELECT l.lin_rep, e.permid, di.rank_id,
               row_number() OVER (PARTITION BY l.lin_rep
                   ORDER BY e.evidence DESC, e.yr DESC NULLS LAST, e.opinion_id DESC) AS rn,
               e.evidence AS acc_ev, e.yr AS acc_yr, e.opinion_id AS acc_id
        FROM _dt_lin l
        JOIN eligible e ON e.permid = l.permid
        JOIN _dt_identity di ON di.permid = e.permid
    )
    SELECT s.lin_rep,
           r.original_permid,
           s.permid AS accepted_spelling_permid,
           s.rank_id AS accepted_rank_id,
           s.acc_ev, s.acc_yr, s.acc_id,
           (SELECT COALESCE(pe2.yr, 999999) FROM _dt_permid_edge pe2
             WHERE pe2.permid = r.original_permid) AS original_yr
    FROM spelling s JOIN roots r ON r.lin_rep = s.lin_rep
    WHERE s.rn = 1;
    CREATE INDEX ON _dt_linmeta(lin_rep);
    ANALYZE _dt_linmeta;

    -- each lineage's own top-ranked CONCEPT-class opinion, pooled across all
    -- of that lineage's member permids (concept membership is a property of
    -- the whole lineage, not of whichever spelling happened to carry the
    -- opinion). As with _dt_lin_winner above, a negating winner's target (sr)
    -- is provenance only and is never read by the union-find below.
    --
    -- A candidate edge is excluded entirely -- on either side -- if either
    -- lineage's accepted rank is unranked(25)/unranked clade(24) (fixed
    -- 2026-08-21, migration_exploration/testing/enumerate-containment-cycles.js;
    -- see openspec/changes/fix-eukarya-eumetazoa-containment-cycle/). These
    -- are cladistic ranks, not part of the Linnaean containment system;
    -- letting one merge into a concept alongside a Linnaean-ranked ancestor
    -- or descendant was the actual mechanism behind 16 of 18 real
    -- containment cycles found in the full-migration dataset (e.g. Eukarya /
    -- Eumetazoa). Checked via _dt_linmeta.accepted_rank_id -- the LINEAGE's
    -- accepted rank -- not the raw opinion's own subject/target permid: a
    -- permid-level check left a loophole (18->4 instead of 18->2) where a
    -- concept's senior spelling is unranked but the specific lineage-mate an
    -- opinion cites as subject/target isn't.
    DROP TABLE IF EXISTS _dt_con_winner;
    CREATE TEMP TABLE _dt_con_winner AS
    WITH cand AS MATERIALIZED (
        SELECT ls.lin_rep AS jr, lt.lin_rep AS sr, n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id, n.negates
        FROM name_opinions n
        JOIN _dt_lin ls ON ls.permid = n.subject_permid
        JOIN _dt_lin lt ON lt.permid = n.target_permid
        JOIN _dt_linmeta lm_s ON lm_s.lin_rep = ls.lin_rep
        JOIN _dt_linmeta lm_t ON lm_t.lin_rep = lt.lin_rep
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL AND n.edge_class = 'concept'
          AND lm_s.accepted_rank_id NOT IN (24, 25) AND lm_t.accepted_rank_id NOT IN (24, 25)
    ),
    ranked AS MATERIALIZED (
        SELECT jr, sr, negates,
               row_number() OVER (PARTITION BY jr
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM cand
    )
    SELECT jr, sr, negates FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dt_con_winner(jr);
    ANALYZE _dt_con_winner;

    -- ---- concept union-find (components over each lineage's own winning, --
    -- non-negating concept edge only -- not every current one) --------------
    -- (con_edge and con_undir are marked MATERIALIZED; reach is the recursive
    -- term itself and can't be inlined regardless, so it's left as-is.)
    DROP TABLE IF EXISTS _dt_con;
    CREATE TEMP TABLE _dt_con AS
    WITH RECURSIVE
    con_edge AS MATERIALIZED (
        SELECT jr, sr FROM _dt_con_winner WHERE negates = false
    ),
    con_undir AS MATERIALIZED (
        SELECT jr AS a, sr AS b FROM con_edge UNION SELECT sr, jr FROM con_edge
    ),
    reach(src, node) AS (
        SELECT DISTINCT lin_rep, lin_rep FROM _dt_lin
        UNION
        SELECT r.src, u.b FROM reach r JOIN con_undir u ON u.a = r.node
    )
    SELECT src AS lin_rep, min(node::text)::uuid AS con_rep FROM reach GROUP BY src;
    CREATE INDEX ON _dt_con(lin_rep);
    CREATE INDEX ON _dt_con(con_rep);
    ANALYZE _dt_con;

    -- ---- validity veto: which lineages are excluded from concept seniority -
    -- (fix-nomen-dubium-concept-seniority) See the identical, static (not
    -- iterative) determination in derive_taxa() for the full rationale.
    DROP TABLE IF EXISTS _dt_lin_invalidated;
    CREATE TEMP TABLE _dt_lin_invalidated AS
    SELECT lm.lin_rep
    FROM _dt_linmeta lm
    WHERE EXISTS (SELECT 1 FROM _dt_permid_invalidated pi WHERE pi.permid = lm.accepted_spelling_permid);
    CREATE INDEX ON _dt_lin_invalidated(lin_rep);
    ANALYZE _dt_lin_invalidated;

    DROP TABLE IF EXISTS _dt_con_all_invalidated;
    CREATE TEMP TABLE _dt_con_all_invalidated AS
    SELECT c.con_rep
    FROM _dt_con c
    GROUP BY c.con_rep
    HAVING bool_and(EXISTS (SELECT 1 FROM _dt_lin_invalidated li WHERE li.lin_rep = c.lin_rep));
    CREATE INDEX ON _dt_con_all_invalidated(con_rep);
    ANALYZE _dt_con_all_invalidated;

    -- Concepts where SOME but not all members are invalidated -- the only
    -- ones whose senior-candidate pool is actually narrowed by validity, and
    -- so the only ones where nomenclatural priority is promoted ahead of the
    -- mechanical acc_ev/acc_yr/acc_id tiebreak below. See the identical
    -- table in derive_taxa() for the full rationale (confirmed live:
    -- excluding an invalid competitor commonly leaves the survivors tied on
    -- sink preference, with nothing left to break the tie but that same
    -- recency-biased mechanical field).
    DROP TABLE IF EXISTS _dt_con_has_invalidated;
    CREATE TEMP TABLE _dt_con_has_invalidated AS
    SELECT DISTINCT c.con_rep
    FROM _dt_con c
    JOIN _dt_lin_invalidated li ON li.lin_rep = c.lin_rep
    WHERE c.con_rep NOT IN (SELECT con_rep FROM _dt_con_all_invalidated);
    CREATE INDEX ON _dt_con_has_invalidated(con_rep);
    ANALYZE _dt_con_has_invalidated;

    -- senior lineage per concept + concept_permid/rank
    DROP TABLE IF EXISTS _dt_conmeta;
    CREATE TEMP TABLE _dt_conmeta AS
    WITH con_sources AS MATERIALIZED (
        -- a lineage counts as "a source" (ever proposed junior) only if its
        -- current winning concept-class opinion is active AND its target is
        -- not invalidated (unless the target's whole concept is
        -- all-invalidated) -- deferring to a lineage that can't win isn't a
        -- genuine deferral
        SELECT DISTINCT cw.jr
        FROM _dt_con_winner cw
        JOIN _dt_con c ON c.lin_rep = cw.jr
        WHERE cw.negates = false
          AND (
            c.con_rep IN (SELECT con_rep FROM _dt_con_all_invalidated)
            OR NOT EXISTS (SELECT 1 FROM _dt_lin_invalidated li WHERE li.lin_rep = cw.sr)
          )
    ),
    ranked AS MATERIALIZED (
        SELECT c.con_rep, c.lin_rep,
               row_number() OVER (PARTITION BY c.con_rep ORDER BY
                   (li.lin_rep IS NULL OR aic.con_rep IS NOT NULL) DESC,      -- validity exclusion
                   (cs.jr IS NULL) DESC,                                     -- non-source (never junior) first
                   CASE WHEN hic.con_rep IS NOT NULL THEN lm.original_yr END ASC NULLS LAST,  -- priority, promoted iff narrowed by validity
                   lm.acc_ev DESC, lm.acc_yr DESC NULLS LAST, lm.acc_id DESC,
                   CASE WHEN hic.con_rep IS NULL THEN lm.original_yr END ASC NULLS LAST,      -- priority, original position otherwise
                   lm.original_permid ASC) AS rn
        FROM _dt_con c
        JOIN _dt_linmeta lm ON lm.lin_rep = c.lin_rep
        LEFT JOIN con_sources cs ON cs.jr = c.lin_rep
        LEFT JOIN _dt_lin_invalidated li ON li.lin_rep = c.lin_rep
        LEFT JOIN _dt_con_all_invalidated aic ON aic.con_rep = c.con_rep
        LEFT JOIN _dt_con_has_invalidated hic ON hic.con_rep = c.con_rep
    )
    SELECT r.con_rep, r.lin_rep AS senior_lin,
           lm.accepted_spelling_permid AS concept_permid,
           lm.accepted_rank_id AS concept_rank_id,
           tr.taxonomy_rank AS concept_rank_name
    FROM ranked r
    JOIN _dt_linmeta lm ON lm.lin_rep = r.lin_rep
    JOIN dictionaries.taxonomy_ranks tr ON tr.id = lm.accepted_rank_id
    WHERE r.rn = 1;
    CREATE INDEX ON _dt_conmeta(con_rep);
    ANALYZE _dt_conmeta;

    -- ---- classification: winning assignment pooled across the concept ------
    -- Self-referential candidates (containing_permid resolves back to the
    -- subject's own concept) are excluded here, before ranking -- not just
    -- detected after (fixed 2026-08-21, migration_exploration/testing/
    -- diagnose-containment-self-loops.js; see
    -- openspec/changes/fix-dt-assign-containment-cycle/). Previously, 73
    -- concepts in the real full-migration dataset ended up with
    -- containing_concept_permid = concept_permid: 71/73 were two
    -- now-synonymized lineages where one carried a legacy assignment opinion
    -- citing the other as container from before the synonymy was recognized;
    -- 2/73 were literal same-lineage self-references (a rank-change lineage
    -- edge unifying a taxon with its own alternate-rank spelling, then a
    -- containment opinion naming that spelling as container). A concept whose
    -- only candidate(s) are self-referential ends up with zero _dt_assign
    -- rows, which the LEFT JOIN below already turns into
    -- containing_concept_permid = NULL (rootless) -- the same outcome already
    -- used elsewhere for "no container asserted".
    --
    -- Candidates are also excluded when either the subject's or the
    -- containing permid's lineage is accepted at rank unranked(25)/unranked
    -- clade(24) (fixed 2026-08-21; see
    -- openspec/changes/fix-eukarya-eumetazoa-containment-cycle/). These
    -- cladistic ranks SHALL NOT be assigned a containing_concept_permid of
    -- their own, and SHALL NOT be eligible to serve as another concept's
    -- container -- the same reasoning as _dt_con_winner's exclusion above,
    -- applied here for the cycles where an unranked concept was on the
    -- containment side rather than (or in addition to) the synonymy side.
    --
    -- Candidates are also excluded on rank cardinality: a container SHALL
    -- NOT be more finely ranked than what it contains. Equal rank is
    -- permitted (e.g. one genus containing another is a legitimate, common
    -- pattern independent of the equal-rank-borrowing branch below) -- only
    -- a genuine inversion (containing lineage strictly finer than the
    -- subject lineage) is excluded. This is what fixed the last 2 real
    -- containment cycles found in the full-migration dataset
    -- (Hyriidae/Hyriinae, Elasmotheriini/Elasmotheriina), neither of which
    -- involved unranked ranks at all -- see
    -- openspec/changes/fix-eukarya-eumetazoa-containment-cycle/.

    -- ---- classification cycle-breaking loop --------------------------------
    -- Rank cardinality and the unranked-clade/self-reference exclusions above
    -- already prevent containment cycles by construction in every case found
    -- against the full-migration dataset to date. This loop is a residual
    -- safety net on top of that, not the primary defense: each iteration
    -- rebuilds _dt_assign/_dt_node excluding whatever opinions prior
    -- iterations have cut, precisely identifies any genuine cycle members (a
    -- concept whose own containment chain returns to ITSELF), and cuts the
    -- SINGLE weakest edge (lowest evidence/pubyr/id by the canonical order)
    -- among all current cycle members' own winning candidates. Repeats until
    -- no cycle remains -- the same MST-style weakest-link loop
    -- derive_taxa_clades() uses for clade-to-clade cycles, including its
    -- iter > 1000 non-convergence guard.
    --
    -- NOTE: the recursive walk below explores from every starting node up to
    -- depth 10000 before checking for a match -- a suspected further
    -- pathology in its own right if many nodes feed into a real cycle (see
    -- find-containment-cycle.js's iterative-peeling alternative), but left as
    -- originally written here since replacing it is a separate question from
    -- this loop.
    DROP TABLE IF EXISTS _dt_excluded_opinions;
    CREATE TEMP TABLE _dt_excluded_opinions (
        opinion_id bigint PRIMARY KEY,
        concept_permid uuid,
        cycle_members uuid[]
    );

    -- optimize-derive-taxa-seed: seed IS NULL keeps the global cycle-breaking
    -- loop and full-tree classification_path build below exactly as before.
    -- For seed IS NOT NULL, the ELSE branch (after this whole loop) replaces
    -- both with an on-demand upward walk scoped to just the con_reps
    -- reachable from the requested permids -- see this change's design.md.
    IF seed IS NULL THEN

    <<cycle_break>>
    LOOP
        -- optimize-derive-taxa-cycle-loop: only the FIRST pass rebuilds
        -- _dt_assign/_dt_node from scratch. Every subsequent pass instead
        -- recomputes just the one con_rep whose previously-winning opinion
        -- was excluded by the PRIOR iteration's cut (affected_con_rep) --
        -- every other con_rep's candidate pool and ranking are provably
        -- unaffected by one more row in _dt_excluded_opinions. See that
        -- change's design.md ("Why the single-con_rep recompute is safe").
        -- _dt_cycle_members below is UNCHANGED and still re-verifies the
        -- whole graph every pass -- a replacement edge can introduce a path
        -- through arbitrary other parts of the graph, so global
        -- cycle re-detection is not something this optimization touches.
        IF affected_con_rep IS NULL THEN
            DROP TABLE IF EXISTS _dt_assign;
            CREATE TEMP TABLE _dt_assign AS
            WITH cand AS MATERIALIZED (
                SELECT cm.con_rep, a.id AS opinion_id, a.containing_permid,
                       a.evidence,
                       COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
                       -- Was this candidate filed on the concept's own senior lineage,
                       -- or only pooled in via the equal-rank-borrowing branch (e.g. a
                       -- junior synonym's own opinion)? Used below to break cycle-cut
                       -- ties toward the borrowed candidate -- see is_senior comment
                       -- on the cut-selection query.
                       (sl.lin_rep = cm.senior_lin) AS is_senior
                FROM assignment_opinions a
                JOIN _dt_lin sl ON sl.permid = a.subject_permid
                JOIN _dt_con  sc ON sc.lin_rep = sl.lin_rep
                JOIN _dt_conmeta cm ON cm.con_rep = sc.con_rep
                JOIN _dt_linmeta lm ON lm.lin_rep = sl.lin_rep
                LEFT JOIN refs r ON r.id = a.reference_id
                LEFT JOIN _dt_lin ccl ON ccl.permid = a.containing_permid
                LEFT JOIN _dt_con ccc ON ccc.lin_rep = ccl.lin_rep
                LEFT JOIN _dt_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
                WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
                  AND ( sl.lin_rep = cm.senior_lin
                        OR (cm.concept_rank_name <> 'species'
                            AND lm.accepted_rank_id = cm.concept_rank_id) )
                  AND ccc.con_rep IS DISTINCT FROM cm.con_rep
                  AND lm.accepted_rank_id NOT IN (24, 25)
                  AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id NOT IN (24, 25))
                  AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id >= lm.accepted_rank_id)
                  AND NOT EXISTS (SELECT 1 FROM _dt_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ),
            win AS MATERIALIZED (
                SELECT con_rep, opinion_id, containing_permid, evidence, yr, is_senior,
                       row_number() OVER (PARTITION BY con_rep
                           ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
                FROM cand
            )
            SELECT w.con_rep, w.opinion_id AS winning_assignment_opinion_id,
                   cc.con_rep AS containing_con_rep, w.evidence, w.yr, w.is_senior
            FROM win w
            LEFT JOIN _dt_lin cl ON cl.permid = w.containing_permid
            LEFT JOIN _dt_con cc ON cc.lin_rep = cl.lin_rep
            WHERE w.rn = 1;
            CREATE INDEX ON _dt_assign(con_rep);
            ANALYZE _dt_assign;

            -- ---- per-concept node (concept_permid, containing_concept_permid) --
            DROP TABLE IF EXISTS _dt_node;
            CREATE TEMP TABLE _dt_node AS
            SELECT cm.con_rep, cm.concept_permid, cm.concept_rank_id,
                   ccm.concept_permid AS containing_concept_permid,
                   a.winning_assignment_opinion_id, a.evidence, a.yr, a.is_senior
            FROM _dt_conmeta cm
            LEFT JOIN _dt_assign a ON a.con_rep = cm.con_rep
            LEFT JOIN _dt_conmeta ccm ON ccm.con_rep = a.containing_con_rep;
            CREATE INDEX ON _dt_node(con_rep);
            CREATE INDEX ON _dt_node(concept_permid);
            CREATE INDEX ON _dt_node(containing_concept_permid);
            ANALYZE _dt_node;
        ELSE
            -- Same cand logic as the full build above, scoped to the one
            -- affected con_rep and simplified accordingly (no PARTITION BY
            -- needed once already scoped to a single con_rep).
            SELECT a.id, a.containing_permid, a.evidence,
                   COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int),
                   (sl.lin_rep = cm.senior_lin)
            INTO new_opinion_id, new_containing_permid, new_evidence, new_yr, new_is_senior
            FROM assignment_opinions a
            JOIN _dt_lin sl ON sl.permid = a.subject_permid
            JOIN _dt_con  sc ON sc.lin_rep = sl.lin_rep
            JOIN _dt_conmeta cm ON cm.con_rep = sc.con_rep AND cm.con_rep = affected_con_rep
            JOIN _dt_linmeta lm ON lm.lin_rep = sl.lin_rep
            LEFT JOIN refs r ON r.id = a.reference_id
            LEFT JOIN _dt_lin ccl ON ccl.permid = a.containing_permid
            LEFT JOIN _dt_con ccc ON ccc.lin_rep = ccl.lin_rep
            LEFT JOIN _dt_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
            WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
              AND ( sl.lin_rep = cm.senior_lin
                    OR (cm.concept_rank_name <> 'species'
                        AND lm.accepted_rank_id = cm.concept_rank_id) )
              AND ccc.con_rep IS DISTINCT FROM cm.con_rep
              AND lm.accepted_rank_id NOT IN (24, 25)
              AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id NOT IN (24, 25))
              AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id >= lm.accepted_rank_id)
              AND NOT EXISTS (SELECT 1 FROM _dt_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ORDER BY a.evidence DESC,
                     COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                     a.id DESC
            LIMIT 1;

            IF new_opinion_id IS NOT NULL THEN
                SELECT cc.con_rep INTO new_containing_con_rep
                FROM _dt_lin cl JOIN _dt_con cc ON cc.lin_rep = cl.lin_rep
                WHERE cl.permid = new_containing_permid;

                UPDATE _dt_assign SET
                    winning_assignment_opinion_id = new_opinion_id,
                    containing_con_rep = new_containing_con_rep,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;

                UPDATE _dt_node SET
                    containing_concept_permid = (SELECT ccm.concept_permid FROM _dt_conmeta ccm
                                                   WHERE ccm.con_rep = new_containing_con_rep),
                    winning_assignment_opinion_id = new_opinion_id,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;
            ELSE
                DELETE FROM _dt_assign WHERE con_rep = affected_con_rep;

                UPDATE _dt_node SET
                    containing_concept_permid = NULL, winning_assignment_opinion_id = NULL,
                    evidence = NULL, yr = NULL, is_senior = NULL
                WHERE con_rep = affected_con_rep;
            END IF;

            new_opinion_id := NULL;
            new_containing_permid := NULL;
            new_containing_con_rep := NULL;
            new_evidence := NULL;
            new_yr := NULL;
            new_is_senior := NULL;
            affected_con_rep := NULL;
        END IF;

        -- ---- cheap survivor set via iterative peeling (optimize-derive-taxa-
        -- cycle-loop) ------------------------------------------------------
        -- The walk below only needs to run from nodes that COULD be cycle
        -- members -- and a genuine cycle member's own container is always
        -- ANOTHER cycle member (the loop is mutually self-supporting), so it
        -- can never be pruned by "delete any node whose own container isn't
        -- itself still present." Survivors = every genuine cycle member plus
        -- everything permanently downstream of one; on real data this is a
        -- tiny fraction of the full node set, turning an O(V x 10000) walk
        -- from every node into one from just the survivors. Same algorithm
        -- derive_taxa() already uses for exactly this reason.
        DROP TABLE IF EXISTS _dt_peel;
        CREATE TEMP TABLE _dt_peel AS
        SELECT con_rep, concept_permid, containing_concept_permid
        FROM _dt_node WHERE containing_concept_permid IS NOT NULL;
        CREATE INDEX ON _dt_peel(concept_permid);
        CREATE INDEX ON _dt_peel(con_rep);
        ANALYZE _dt_peel;

        <<peel>>
        LOOP
            DELETE FROM _dt_peel a
            WHERE NOT EXISTS (SELECT 1 FROM _dt_peel b WHERE b.concept_permid = a.containing_concept_permid);
            GET DIAGNOSTICS peeled_count = ROW_COUNT;
            EXIT peel WHEN peeled_count = 0;
        END LOOP peel;

        -- genuine cycle members this round (a concept whose own containment
        -- chain returns to ITSELF), materialized so both the weakest-edge
        -- pick below and the audit log can reuse it. Sourced from _dt_peel
        -- (survivors only) rather than _dt_node -- identical result, since
        -- every genuine cycle member is provably a survivor, but the walk
        -- only has to consider the (usually far smaller) survivor set.
        DROP TABLE IF EXISTS _dt_cycle_members;
        CREATE TEMP TABLE _dt_cycle_members AS
        WITH RECURSIVE walk AS (
            SELECT con_rep AS start_rep, containing_concept_permid, 1 AS depth
            FROM _dt_peel
            UNION ALL
            SELECT w.start_rep, n.containing_concept_permid, w.depth + 1
            FROM walk w
            JOIN _dt_peel cn ON cn.concept_permid = w.containing_concept_permid
            JOIN _dt_peel n  ON n.con_rep = cn.con_rep
            WHERE w.depth < 10000
        )
        SELECT DISTINCT w.start_rep AS con_rep
        FROM walk w
        JOIN _dt_peel self ON self.con_rep = w.start_rep
        WHERE w.containing_concept_permid = self.concept_permid;

        -- find the weakest winning edge among this round's genuine cycle
        -- members (NULL if none remain). On an evidence/pubyr tie, prefer
        -- cutting an edge borrowed from a pooled/junior lineage (is_senior
        -- false) over one filed directly on the concept's own senior lineage
        -- (is_senior true) -- a borrowed edge is more likely to be a
        -- synonym-pooling artifact than a real disagreement about the anchor
        -- name itself. Falls back to opinion_id (arbitrary, last resort) only
        -- when even that ties. See the Ornithopoda/Clypeodonta case in
        -- docs/clade-hierarchy-user-guide.html: the cycle there was created
        -- by a junior synonym's own opinion being pooled into the anchor
        -- concept, not by the anchor concept's own opinions disagreeing.
        -- Also captures which con_rep that edge belongs to (affected_con_rep)
        -- -- optimize-derive-taxa-cycle-loop's incremental recompute on the
        -- next pass needs it.
        SELECT a.winning_assignment_opinion_id, a.con_rep INTO cut_opinion_id, affected_con_rep
        FROM _dt_cycle_members cyc
        JOIN _dt_node a ON a.con_rep = cyc.con_rep
        ORDER BY a.evidence ASC, a.yr ASC NULLS FIRST, a.is_senior ASC, a.winning_assignment_opinion_id ASC
        LIMIT 1;

        EXIT cycle_break WHEN cut_opinion_id IS NULL;

        INSERT INTO _dt_excluded_opinions (opinion_id, concept_permid, cycle_members)
        SELECT cut_opinion_id,
               (SELECT nd.concept_permid FROM _dt_node nd
                WHERE nd.winning_assignment_opinion_id = cut_opinion_id LIMIT 1),
               (SELECT array_agg(DISTINCT nd2.concept_permid)
                FROM _dt_cycle_members cm2 JOIN _dt_node nd2 ON nd2.con_rep = cm2.con_rep);
        cut_opinion_id := NULL;

        iter := iter + 1;
        IF iter > 1000 THEN
            RAISE EXCEPTION 'derive_linnaean: classification cycle-breaking loop did not converge after 1000 iterations';
        END IF;
    END LOOP cycle_break;

    -- ---- classification_path (root -> node) -------------------------------
    DROP TABLE IF EXISTS _dt_path;
    CREATE TEMP TABLE _dt_path AS
    WITH RECURSIVE p AS (
        SELECT con_rep, concept_permid, containing_concept_permid,
               text2ltree(replace(concept_permid::text,'-','_')) AS classification_path
        FROM _dt_node WHERE containing_concept_permid IS NULL
        UNION ALL
        SELECT cn.con_rep, cn.concept_permid, cn.containing_concept_permid,
               pp.classification_path || replace(cn.concept_permid::text,'-','_')
        FROM _dt_node cn
        JOIN _dt_node parent ON parent.concept_permid = cn.containing_concept_permid
        JOIN p pp ON pp.con_rep = parent.con_rep
    )
    SELECT con_rep, classification_path FROM p;
    CREATE INDEX ON _dt_path(con_rep);
    ANALYZE _dt_path;

    ELSE
        -- ---- seed-scoped: which con_reps the RETURN QUERY below will actually
        -- need -- computed once, up front, from the (unscoped) identity/
        -- lineage/concept union-find already built above, not re-derived per
        -- permid inside the walk.
        DROP TABLE IF EXISTS _dt_seed_con_reps;
        CREATE TEMP TABLE _dt_seed_con_reps AS
        SELECT DISTINCT c.con_rep
        FROM _dt_identity m
        JOIN _dt_lin l ON l.permid = m.permid
        JOIN _dt_con c ON c.lin_rep = l.lin_rep
        WHERE m.permid = ANY(seed);
        CREATE INDEX ON _dt_seed_con_reps(con_rep);
        ANALYZE _dt_seed_con_reps;

        -- Sparse counterpart of the global _dt_node table above -- same
        -- columns, but only ever gains a row for a con_rep actually visited
        -- by a walk below, so the RETURN QUERY at the bottom of this
        -- function needs no branching of its own between the two paths.
        DROP TABLE IF EXISTS _dt_node;
        CREATE TEMP TABLE _dt_node (
            con_rep uuid PRIMARY KEY,
            concept_permid uuid,
            concept_rank_id integer,
            containing_concept_permid uuid,
            winning_assignment_opinion_id bigint,
            evidence boolean,
            yr integer,
            is_senior boolean
        );
        CREATE INDEX ON _dt_node(concept_permid);
        CREATE INDEX ON _dt_node(containing_concept_permid);

        -- One walk per distinct con_rep the seed actually needs. A con_rep
        -- already resolved by an earlier seed's walk in this same call is
        -- skipped outright -- see derive_taxa()'s identical ELSE branch and
        -- design.md's correctness argument for why a cached con_rep can
        -- safely be trusted without re-walking.
        <<swalk_seed_loop>>
        FOR swalk_seed_con_rep IN SELECT con_rep FROM _dt_seed_con_reps LOOP
            IF EXISTS (SELECT 1 FROM _dt_node WHERE con_rep = swalk_seed_con_rep) THEN
                CONTINUE swalk_seed_loop;
            END IF;

            DROP TABLE IF EXISTS _dt_swalk_stack;
            CREATE TEMP TABLE _dt_swalk_stack (
                step integer PRIMARY KEY,
                con_rep uuid,
                concept_permid uuid,
                concept_rank_id integer,
                containing_concept_permid uuid,
                winning_assignment_opinion_id bigint,
                evidence boolean,
                yr integer,
                is_senior boolean
            );
            CREATE INDEX ON _dt_swalk_stack(con_rep);

            swalk_con_rep := swalk_seed_con_rep;
            swalk_step := 0;
            swalk_iter := 0;

            -- Climb containing_concept_permid one step at a time, resolving
            -- each con_rep on demand via the same single-con_rep candidate
            -- query the seed IS NULL branch's incremental ELSE above uses,
            -- generalized to any con_rep rather than hardcoded to
            -- affected_con_rep. A revisit of a con_rep already on THIS
            -- walk's own stack is a genuine local cycle: cut its weakest
            -- edge (same tiebreak order the global cycle-break loop above
            -- uses) and restart the WHOLE walk from the seed, not from the
            -- cut point -- see derive_taxa()'s identical logic and
            -- design.md's Context for why a cut can expose a different,
            -- larger cycle further up. (Live profiling found this
            -- function's cycle loop currently cuts nothing at all against
            -- the real dataset -- iter=0 -- so this path is structurally
            -- identical to derive_taxa()'s proven-correct one but not
            -- exercised by any live cycle today.)
            <<swalk_climb>>
            LOOP
                SELECT EXISTS (SELECT 1 FROM _dt_node WHERE con_rep = swalk_con_rep) INTO swalk_cached;
                IF swalk_cached THEN
                    EXIT swalk_climb;
                END IF;

                SELECT step INTO swalk_cycle_start_step FROM _dt_swalk_stack WHERE con_rep = swalk_con_rep;
                IF swalk_cycle_start_step IS NOT NULL THEN
                    SELECT s.winning_assignment_opinion_id INTO swalk_cut_opinion_id
                    FROM _dt_swalk_stack s
                    WHERE s.step >= swalk_cycle_start_step
                    ORDER BY s.evidence ASC, s.yr ASC NULLS FIRST, s.is_senior ASC, s.winning_assignment_opinion_id ASC
                    LIMIT 1;

                    INSERT INTO _dt_excluded_opinions (opinion_id, concept_permid, cycle_members)
                    SELECT swalk_cut_opinion_id,
                           (SELECT s2.concept_permid FROM _dt_swalk_stack s2
                            WHERE s2.winning_assignment_opinion_id = swalk_cut_opinion_id LIMIT 1),
                           (SELECT array_agg(DISTINCT s3.concept_permid)
                            FROM _dt_swalk_stack s3 WHERE s3.step >= swalk_cycle_start_step);

                    swalk_iter := swalk_iter + 1;
                    IF swalk_iter > 1000 THEN
                        RAISE EXCEPTION 'derive_linnaean: seed-scoped cycle resolution for con_rep % did not converge after 1000 cuts',
                            swalk_seed_con_rep;
                    END IF;

                    DELETE FROM _dt_swalk_stack;
                    swalk_con_rep := swalk_seed_con_rep;
                    swalk_step := 0;
                    CONTINUE swalk_climb;
                END IF;

                -- Same cand logic as the global build's ELSE branch above,
                -- scoped to swalk_con_rep instead of affected_con_rep.
                SELECT cm.concept_permid, cm.concept_rank_id INTO swalk_concept_permid, swalk_concept_rank_id
                FROM _dt_conmeta cm WHERE cm.con_rep = swalk_con_rep;

                SELECT a.id, a.containing_permid, a.evidence,
                       COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int),
                       (sl.lin_rep = cm.senior_lin)
                INTO swalk_new_opinion_id, swalk_new_containing_permid, swalk_new_evidence, swalk_new_yr, swalk_new_is_senior
                FROM assignment_opinions a
                JOIN _dt_lin sl ON sl.permid = a.subject_permid
                JOIN _dt_con  sc ON sc.lin_rep = sl.lin_rep
                JOIN _dt_conmeta cm ON cm.con_rep = sc.con_rep AND cm.con_rep = swalk_con_rep
                JOIN _dt_linmeta lm ON lm.lin_rep = sl.lin_rep
                LEFT JOIN refs r ON r.id = a.reference_id
                LEFT JOIN _dt_lin ccl ON ccl.permid = a.containing_permid
                LEFT JOIN _dt_con ccc ON ccc.lin_rep = ccl.lin_rep
                LEFT JOIN _dt_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
                WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
                  AND ( sl.lin_rep = cm.senior_lin
                        OR (cm.concept_rank_name <> 'species'
                            AND lm.accepted_rank_id = cm.concept_rank_id) )
                  AND ccc.con_rep IS DISTINCT FROM cm.con_rep
                  AND lm.accepted_rank_id NOT IN (24, 25)
                  AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id NOT IN (24, 25))
                  AND (ccm.accepted_rank_id IS NULL OR ccm.accepted_rank_id >= lm.accepted_rank_id)
                  AND NOT EXISTS (SELECT 1 FROM _dt_excluded_opinions eo WHERE eo.opinion_id = a.id)
                ORDER BY a.evidence DESC,
                         COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                         a.id DESC
                LIMIT 1;

                IF swalk_new_opinion_id IS NOT NULL THEN
                    SELECT cc.con_rep, ccm2.concept_permid
                    INTO swalk_new_containing_con_rep, swalk_new_containing_concept_permid
                    FROM _dt_lin cl
                    JOIN _dt_con cc ON cc.lin_rep = cl.lin_rep
                    JOIN _dt_conmeta ccm2 ON ccm2.con_rep = cc.con_rep
                    WHERE cl.permid = swalk_new_containing_permid;
                ELSE
                    swalk_new_containing_con_rep := NULL;
                    swalk_new_containing_concept_permid := NULL;
                END IF;

                INSERT INTO _dt_swalk_stack (step, con_rep, concept_permid, concept_rank_id,
                    containing_concept_permid, winning_assignment_opinion_id, evidence, yr, is_senior)
                VALUES (swalk_step, swalk_con_rep, swalk_concept_permid, swalk_concept_rank_id,
                    swalk_new_containing_concept_permid, swalk_new_opinion_id, swalk_new_evidence, swalk_new_yr, swalk_new_is_senior);

                EXIT swalk_climb WHEN swalk_new_containing_concept_permid IS NULL;

                swalk_con_rep := swalk_new_containing_con_rep;
                swalk_step := swalk_step + 1;
            END LOOP swalk_climb;

            INSERT INTO _dt_node
            SELECT con_rep, concept_permid, concept_rank_id, containing_concept_permid,
                   winning_assignment_opinion_id, evidence, yr, is_senior
            FROM _dt_swalk_stack;
        END LOOP swalk_seed_loop;

        DROP TABLE IF EXISTS _dt_swalk_stack;

        -- ---- classification_path, scoped to just the requested con_reps ---
        -- Bottom-up analog of the global build above: climbs containing_
        -- concept_permid pointers from each requested con_rep up through the
        -- now fully-populated (but still sparse) _dt_node, prepending each
        -- ancestor's own label as it goes -- so the final (deepest) row per
        -- con_rep is already in root-to-node order, no separate reversal
        -- step needed.
        DROP TABLE IF EXISTS _dt_path;
        CREATE TEMP TABLE _dt_path AS
        WITH RECURSIVE p AS (
            SELECT sc.con_rep AS seed_con_rep, n.concept_permid AS cur_concept_permid,
                   n.containing_concept_permid AS cur_containing,
                   text2ltree(replace(n.concept_permid::text,'-','_')) AS classification_path
            FROM _dt_seed_con_reps sc
            JOIN _dt_node n ON n.con_rep = sc.con_rep
            UNION ALL
            SELECT p.seed_con_rep, parent.concept_permid, parent.containing_concept_permid,
                   text2ltree(replace(parent.concept_permid::text,'-','_')) || p.classification_path
            FROM p
            JOIN _dt_node parent ON parent.concept_permid = p.cur_containing
        )
        SELECT DISTINCT ON (seed_con_rep) seed_con_rep AS con_rep, classification_path
        FROM p ORDER BY seed_con_rep, nlevel(classification_path) DESC;
        CREATE INDEX ON _dt_path(con_rep);
        ANALYZE _dt_path;
    END IF;

    -- ---- assemble one row per minted permid -------------------------------
    RETURN QUERY
    SELECT
        m.permid,
        m.new_name,
        m.rank_id,
        m.authority_id,
        lm.original_permid,
        lm.accepted_spelling_permid,
        cm.concept_permid,
        nd.containing_concept_permid,
        pth.classification_path,
        vv.nomenclatural_status_id,
        pe.opinion_id AS winning_name_opinion_id,
        nd.winning_assignment_opinion_id,
        vv.winning_validity_opinion_id
    FROM _dt_identity m
    JOIN _dt_permid_edge pe ON pe.permid = m.permid
    JOIN _dt_lin      l   ON l.permid = m.permid
    JOIN _dt_linmeta  lm  ON lm.lin_rep = l.lin_rep
    JOIN _dt_con      c   ON c.lin_rep = l.lin_rep
    JOIN _dt_conmeta  cm  ON cm.con_rep = c.con_rep
    JOIN _dt_node     nd  ON nd.con_rep = c.con_rep
    LEFT JOIN _dt_path pth ON pth.con_rep = c.con_rep
    LEFT JOIN _dt_valid vv ON vv.permid = m.permid
    WHERE seed IS NULL OR m.permid = ANY(seed);
END;
$fn$;


-- ============================================================================
-- rebuild_linnaean() — cold path: derive(all) → upsert into the ledger
-- ============================================================================
CREATE OR REPLACE FUNCTION rebuild_linnaean()
RETURNS integer LANGUAGE plpgsql AS $fn$
DECLARE
    changed integer := 0;
    deleted integer := 0;
BEGIN
    -- Materialize derive_linnaean()'s output once, so the insert/update below
    -- and the orphan deletion further down both read the same snapshot
    -- instead of calling derive_linnaean(NULL) twice.
    DROP TABLE IF EXISTS _rebuild_linnaean_src;
    CREATE TEMP TABLE _rebuild_linnaean_src AS SELECT * FROM derive_linnaean(NULL);

    -- Insert a row for every permid in the snapshot; where the permid
    -- already has a row, update it in place. The DO UPDATE ... WHERE guard makes
    -- this a true no-op (0 rows touched, per Postgres's own ON CONFLICT row-count
    -- semantics) when nothing has actually changed.
    INSERT INTO taxa_linnaean (permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        classification_path, nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id)
    SELECT permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        classification_path, nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id
    FROM _rebuild_linnaean_src
    ON CONFLICT (permid) DO UPDATE SET
        name                          = EXCLUDED.name,
        rank_id                       = EXCLUDED.rank_id,
        authority_id                  = EXCLUDED.authority_id,
        original_permid               = EXCLUDED.original_permid,
        accepted_spelling_permid      = EXCLUDED.accepted_spelling_permid,
        concept_permid                = EXCLUDED.concept_permid,
        containing_concept_permid     = EXCLUDED.containing_concept_permid,
        classification_path           = EXCLUDED.classification_path,
        nomenclatural_status_id       = EXCLUDED.nomenclatural_status_id,
        winning_name_opinion_id       = EXCLUDED.winning_name_opinion_id,
        winning_assignment_opinion_id = EXCLUDED.winning_assignment_opinion_id,
        winning_validity_opinion_id   = EXCLUDED.winning_validity_opinion_id
    WHERE taxa_linnaean.name                      IS DISTINCT FROM EXCLUDED.name
       OR taxa_linnaean.rank_id                   IS DISTINCT FROM EXCLUDED.rank_id
       OR taxa_linnaean.authority_id              IS DISTINCT FROM EXCLUDED.authority_id
       OR taxa_linnaean.original_permid           IS DISTINCT FROM EXCLUDED.original_permid
       OR taxa_linnaean.accepted_spelling_permid  IS DISTINCT FROM EXCLUDED.accepted_spelling_permid
       OR taxa_linnaean.concept_permid            IS DISTINCT FROM EXCLUDED.concept_permid
       OR taxa_linnaean.containing_concept_permid IS DISTINCT FROM EXCLUDED.containing_concept_permid
       OR taxa_linnaean.classification_path       IS DISTINCT FROM EXCLUDED.classification_path
       OR taxa_linnaean.nomenclatural_status_id   IS DISTINCT FROM EXCLUDED.nomenclatural_status_id
       OR taxa_linnaean.winning_name_opinion_id       IS DISTINCT FROM EXCLUDED.winning_name_opinion_id
       OR taxa_linnaean.winning_assignment_opinion_id IS DISTINCT FROM EXCLUDED.winning_assignment_opinion_id
       OR taxa_linnaean.winning_validity_opinion_id   IS DISTINCT FROM EXCLUDED.winning_validity_opinion_id;
    GET DIAGNOSTICS changed = ROW_COUNT;

    -- Remove rows for permids no longer produced by derive_linnaean() -- e.g.
    -- a lineage that lost its last remaining candidate. The upsert above has
    -- no way to detect or handle this: ON CONFLICT only ever inserts/updates.
    DELETE FROM taxa_linnaean t
    WHERE NOT EXISTS (SELECT 1 FROM _rebuild_linnaean_src s WHERE s.permid = t.permid);
    GET DIAGNOSTICS deleted = ROW_COUNT;
    changed := changed + deleted;

    -- Snapshot this run's cuts (left behind in _dt_excluded_opinions by the
    -- derive_linnaean() call above, in this same session) into the permanent log.
    DELETE FROM cycle_cuts WHERE source = 'taxa_linnaean';
    INSERT INTO cycle_cuts (source, concept_permid, cut_opinion_id, cycle_members)
    SELECT 'taxa_linnaean', concept_permid, opinion_id, cycle_members FROM _dt_excluded_opinions;

    RETURN changed;
END;
$fn$;


-- ============================================================================
-- assert_linnaean_invariant() — derive(all) ≡ the current taxa_linnaean rows
-- ============================================================================
CREATE OR REPLACE FUNCTION assert_linnaean_invariant()
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
    bad integer;
BEGIN
    WITH d AS (SELECT * FROM derive_linnaean(NULL)),
    heads AS (SELECT * FROM taxa_linnaean),
    mism AS (
        SELECT COALESCE(d.permid, h.permid) AS permid FROM d
        FULL JOIN heads h ON h.permid = d.permid
        WHERE d.permid IS NULL OR h.permid IS NULL
           OR h.name IS DISTINCT FROM d.name
           OR h.rank_id IS DISTINCT FROM d.rank_id
           OR h.original_permid IS DISTINCT FROM d.original_permid
           OR h.accepted_spelling_permid IS DISTINCT FROM d.accepted_spelling_permid
           OR h.concept_permid IS DISTINCT FROM d.concept_permid
           OR h.containing_concept_permid IS DISTINCT FROM d.containing_concept_permid
           OR h.classification_path IS DISTINCT FROM d.classification_path
           OR h.nomenclatural_status_id IS DISTINCT FROM d.nomenclatural_status_id
    )
    SELECT count(*) INTO bad FROM mism;
    IF bad > 0 THEN
        RAISE EXCEPTION 'assert_linnaean_invariant: % permid(s) diverge between derive_linnaean(all) and the current taxa_linnaean rows', bad;
    END IF;
END;
$fn$;


-- ============================================================================
-- taxa_clades — the clade-to-clade hierarchy derive_linnaean() excludes
-- ============================================================================
-- `derive_linnaean()`'s concept-grouping and classification-pooling both exclude any
-- candidate edge where either side is accepted at rank `unranked`(25)/`unranked
-- clade`(24) -- these cladistic ranks aren't part of the Linnaean containment
-- system (see the concept-grouping and classification-pooling requirements in
-- openspec/specs/taxa-opinions/spec.md). That leaves every unranked lineage an
-- isolated, rootless singleton concept in `taxa_linnaean`, with no derived
-- clade-to-clade synonymy or containment at all -- even though clade-to-clade
-- opinions asserting both are common in the data. `taxa_clades` is the parallel
-- ledger for exactly that: same evidence/pubyr/id winner-selection machinery as
-- `derive_linnaean()`, scoped to rank 24/25 lineages only. See
-- openspec/changes/derive-clade-attachments/{proposal,design}.md and
-- specs/taxa-clades/spec.md for the full rationale and requirements.
--
-- ONE ROW PER MINTED CLADE PERMID, mirroring `taxa_linnaean` exactly (not one row
-- per concept -- an earlier version of this table used that shape, but a
-- concept-only table left junior clade synonym spellings unresolvable by
-- permid, which `derive_clade_attachments()` needs; see
-- openspec/changes/derive-clade-attachments/design.md). Every permid sharing
-- a lineage/concept carries the SAME original_permid/accepted_spelling_permid/
-- concept_permid/containing_concept_permid/winning_assignment_opinion_id --
-- concept-level facts, repeated per row, same as `taxa_linnaean` does for
-- Linnaean concepts. Pure materialized output, hence no authorizer/enterer,
-- same as `taxa_linnaean`. No classification_path -- no consumer needs it yet.
CREATE TABLE taxa_clades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permid uuid NOT NULL CHECK ((get_byte(uuid_send(permid), 6) >> 4) = 7),

    -- IMMUTABLE identity, denormalized from this permid's minting name_opinion
    -- (via `taxa_linnaean` -- not recomputed; see derive_taxa_clades()). rank_id is
    -- this PERMID's own minted rank, which is NOT constrained to 24/25: a
    -- rerank-history lineage can link permids minted at genuinely different
    -- ranks into one lineage (e.g. a family-rank permid reranked over time
    -- into a lineage whose ACCEPTED spelling is now unranked clade) -- the
    -- 24/25 restriction applies to the LINEAGE's accepted rank (the
    -- accepted_spelling_permid's own rank_id in `taxa_linnaean`), not to every
    -- member permid's own rank_id. Confirmed against real pg_play data: e.g.
    -- "Baurusuchinae" (rank_id 7) belongs to a lineage whose
    -- accepted_spelling_permid is accepted at unranked clade.
    name text NOT NULL,
    rank_id integer REFERENCES dictionaries.taxonomy_ranks("id") NOT NULL,
    authority_id bigint REFERENCES authorities("id"),

    original_permid uuid NOT NULL,
    accepted_spelling_permid uuid NOT NULL,
    concept_permid uuid NOT NULL,

    -- Classification within the clade-to-clade hierarchy only. Plain uuid
    -- pointer, not a SQL foreign key -- same convention as taxa.containing_concept_permid.
    containing_concept_permid uuid,        -- NULL = root

    nomenclatural_status_id integer REFERENCES dictionaries.nomenclatural_statuses("id"),

    winning_name_opinion_id       bigint REFERENCES name_opinions("id"),
    winning_assignment_opinion_id bigint REFERENCES assignment_opinions("id"),
    winning_validity_opinion_id   bigint REFERENCES validity_opinions("id"),

    created_at timestamptz DEFAULT NOW(),

    UNIQUE (permid)
);

-- NOT versioned -- a plain cache, one row per clade permid, upserted in place by
-- rebuild_taxa_clades() (same pattern as `taxa_linnaean`/rebuild_linnaean()).


-- ============================================================================
-- derive_taxa_clades() — pure function computing the clade-to-clade hierarchy
-- ============================================================================
-- optimize-derive-taxa-seed: unlike derive_taxa()/derive_linnaean(), `permids`
-- here still just filters the final result -- the seed-scoped upward-walk
-- redesign applied to those two functions was deliberately NOT ported here.
-- Live profiling (2026-09-03) found this function's full, unscoped cost is
-- already only ~7.6s (its graph is a couple orders of magnitude smaller --
-- ~2,525 clade-rank taxa vs ~500K concepts), comfortably inside the "low
-- tens of seconds" bar this change targets, so a third bespoke walk
-- implementation wasn't judged worth the added maintenance surface. See
-- openspec/changes/optimize-derive-taxa-seed/tasks.md, 4.1.
CREATE OR REPLACE FUNCTION derive_taxa_clades(permids uuid[] DEFAULT NULL)
RETURNS TABLE (
    permid uuid,
    name text,
    rank_id integer,
    authority_id bigint,
    original_permid uuid,
    accepted_spelling_permid uuid,
    concept_permid uuid,
    containing_concept_permid uuid,
    nomenclatural_status_id integer,
    winning_name_opinion_id bigint,
    winning_assignment_opinion_id bigint,
    winning_validity_opinion_id bigint
) LANGUAGE plpgsql AS $fn$
#variable_conflict use_column
DECLARE
    cut_opinion_id bigint;
    iter integer := 0;
    peeled_count integer;
    -- optimize-derive-taxa-cycle-loop: incremental _dtc_assign/_dtc_node
    -- recompute after the first loop pass (see that change's design.md).
    affected_con_rep uuid;
    new_opinion_id bigint;
    new_containing_con_rep uuid;
    new_evidence boolean;
    new_yr integer;
    new_is_senior boolean;
BEGIN
    -- ---- lineage identity: reused from `taxa_linnaean`, not recomputed ------
    -- `taxa_linnaean` is per-minted-permid, but the row where permid =
    -- accepted_spelling_permid IS the lineage's own representative row: its
    -- rank_id is that permid's own minted identity, which is exactly the
    -- lineage's accepted rank, and it's unique per original_permid by
    -- construction (derive_linnaean() already selects exactly one
    -- accepted_spelling_permid per lineage). Lineage grouping itself
    -- (name_opinions 'name'-class edges, _dt_lin in derive_linnaean()) is
    -- rank-agnostic and already correct here -- recomputing it would be pure
    -- duplication.
    --
    -- acc_ev/acc_yr/acc_id (the accepted spelling's own canonical introducing
    -- opinion's evidence/pubyr/id) and original_yr (the lineage's original permid's
    -- own introducing opinion's pubyr, falling back to 999999 when unknown, so an
    -- unknown year never wins an ASC "oldest" tiebreak) are pulled in for the
    -- seniority tiebreak below, mirroring derive_linnaean()'s
    -- _dt_linmeta.acc_ev/acc_yr/acc_id/original_yr exactly.
    DROP TABLE IF EXISTS _dtc_lineage;
    CREATE TEMP TABLE _dtc_lineage AS
    SELECT t.original_permid,
           t.accepted_spelling_permid,
           t.name,
           t.rank_id AS accepted_rank_id,
           t.nomenclatural_status_id,
           t.winning_name_opinion_id,
           t.winning_validity_opinion_id,
           acc_no.evidence AS acc_ev,
           COALESCE(acc_no.publication_year, NULLIF(acc_ref.reference->>'publicationYear','')::int) AS acc_yr,
           t.winning_name_opinion_id AS acc_id,
           COALESCE(orig_no.publication_year, NULLIF(orig_ref.reference->>'publicationYear','')::int, 999999) AS original_yr
    FROM taxa_linnaean t
    LEFT JOIN name_opinions acc_no ON acc_no.id = t.winning_name_opinion_id
    LEFT JOIN refs acc_ref ON acc_ref.id = acc_no.reference_id
    LEFT JOIN taxa_linnaean ot ON ot.permid = t.original_permid
    LEFT JOIN name_opinions orig_no ON orig_no.id = ot.winning_name_opinion_id
    LEFT JOIN refs orig_ref ON orig_ref.id = orig_no.reference_id
    WHERE t.permid = t.accepted_spelling_permid
      AND t.rank_id IN (24, 25);
    CREATE UNIQUE INDEX ON _dtc_lineage(original_permid);
    CREATE INDEX ON _dtc_lineage(accepted_spelling_permid);
    ANALYZE _dtc_lineage;

    -- ---- permid -> lineage map, restricted to clade lineages ---------------
    -- The analog of derive_linnaean()'s _dt_lin, but reused from `taxa_linnaean`
    -- (every permid's own row already carries original_permid) rather than
    -- recomputed, and restricted to permids whose lineage is in _dtc_lineage
    -- (i.e. accepted at rank 24/25). Joining on this table is what enforces
    -- "both sides must be a clade lineage" below -- a candidate touching a
    -- Linnaean-ranked permid simply fails to join, the inverse of
    -- derive_linnaean()'s explicit NOT IN (24,25) exclusion.
    DROP TABLE IF EXISTS _dtc_permid_lineage;
    CREATE TEMP TABLE _dtc_permid_lineage AS
    SELECT t.permid, t.original_permid
    FROM taxa_linnaean t
    JOIN _dtc_lineage cl ON cl.original_permid = t.original_permid;
    CREATE INDEX ON _dtc_permid_lineage(permid);
    CREATE INDEX ON _dtc_permid_lineage(original_permid);
    ANALYZE _dtc_permid_lineage;

    -- ---- best concept-class opinion targeting each clade lineage -----------
    -- (fix-nomen-dubium-concept-seniority, ported from derive_taxa()/
    -- derive_linnaean() -- this function's own concept-seniority tiebreak
    -- below never received that fix.) For each clade lin_rep, the best-rated
    -- (evidence DESC, yr DESC, id DESC) current, non-negating concept-class
    -- opinion whose target resolves to it -- counter-signal (b) for the
    -- validity veto below. Scoped to _dtc_permid_lineage on both sides,
    -- matching _dtc_con_winner's own scope.
    DROP TABLE IF EXISTS _dtc_concept_target_best;
    CREATE TEMP TABLE _dtc_concept_target_best AS
    WITH cand AS MATERIALIZED (
        SELECT lt.original_permid AS lin_rep,
               n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id,
               row_number() OVER (PARTITION BY lt.original_permid
                   ORDER BY n.evidence DESC,
                            COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                            n.id DESC) AS rn
        FROM name_opinions n
        JOIN _dtc_permid_lineage ls ON ls.permid = n.subject_permid
        JOIN _dtc_permid_lineage lt ON lt.permid = n.target_permid
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
          AND n.edge_class = 'concept' AND n.negates = false
    )
    SELECT lin_rep, evidence, yr, opinion_id FROM cand WHERE rn = 1;
    CREATE INDEX ON _dtc_concept_target_best(lin_rep);
    ANALYZE _dtc_concept_target_best;

    -- ---- concept grouping (clade-to-clade synonymy union-find) -------------
    -- Mirrors derive_linnaean()'s _dt_con_winner: each lineage's own top-ranked current
    -- concept-class opinion, pooled across all of that lineage's member permids
    -- (the join below naturally pools, since every permid sharing a lin_rep
    -- contributes a candidate row). Restricted to BOTH sides resolving into
    -- _dtc_permid_lineage (both rank 24/25) via the INNER JOINs -- the inverse of
    -- derive_linnaean()'s exclusion, which drops the edge if EITHER side is unranked.
    DROP TABLE IF EXISTS _dtc_con_winner;
    CREATE TEMP TABLE _dtc_con_winner AS
    WITH cand AS MATERIALIZED (
        SELECT ls.original_permid AS jr, lt.original_permid AS sr, n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id, n.negates
        FROM name_opinions n
        JOIN _dtc_permid_lineage ls ON ls.permid = n.subject_permid
        JOIN _dtc_permid_lineage lt ON lt.permid = n.target_permid
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL AND n.edge_class = 'concept'
    ),
    ranked AS MATERIALIZED (
        SELECT jr, sr, negates,
               row_number() OVER (PARTITION BY jr
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM cand
    )
    SELECT jr, sr, negates FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dtc_con_winner(jr);
    ANALYZE _dtc_con_winner;

    -- ---- concept union-find (components over each lineage's own winning, --
    -- non-negating concept edge only) ----------------------------------------
    DROP TABLE IF EXISTS _dtc_con;
    CREATE TEMP TABLE _dtc_con AS
    WITH RECURSIVE
    con_edge AS MATERIALIZED (
        SELECT jr, sr FROM _dtc_con_winner WHERE negates = false
    ),
    con_undir AS MATERIALIZED (
        SELECT jr AS a, sr AS b FROM con_edge UNION SELECT sr, jr FROM con_edge
    ),
    reach(src, node) AS (
        SELECT original_permid, original_permid FROM _dtc_lineage
        UNION
        SELECT r.src, u.b FROM reach r JOIN con_undir u ON u.a = r.node
    )
    SELECT src AS lin_rep, min(node::text)::uuid AS con_rep FROM reach GROUP BY src;
    CREATE INDEX ON _dtc_con(lin_rep);
    CREATE INDEX ON _dtc_con(con_rep);
    ANALYZE _dtc_con;

    -- ---- validity veto: which clade lineages are excluded from concept ----
    -- seniority (fix-nomen-dubium-concept-seniority, ported from
    -- derive_taxa()/derive_linnaean()). A lineage whose accepted spelling's
    -- winning validity opinion (already resolved by derive_linnaean() and
    -- reused here via _dtc_lineage) has invalidates = true is excluded from
    -- senior candidacy only if that opinion's own rating outranks the best
    -- of (a) the accepted spelling's own canonical introducing edge
    -- (_dtc_lineage.acc_ev/acc_yr/acc_id) and (b) any live, non-negating
    -- clade concept-class opinion naming this lineage as target
    -- (_dtc_concept_target_best) -- unless every candidate lineage in the
    -- concept is invalidated (the escape hatch below). Static, not
    -- iterative, for the same reason as derive_taxa()'s own veto: it never
    -- depends on who wins any ranking contest.
    DROP TABLE IF EXISTS _dtc_lin_invalidated;
    CREATE TEMP TABLE _dtc_lin_invalidated AS
    SELECT cl.original_permid AS lin_rep
    FROM _dtc_lineage cl
    JOIN dictionaries.nomenclatural_statuses ns ON ns.id = cl.nomenclatural_status_id
    JOIN validity_opinions v ON v.id = cl.winning_validity_opinion_id
    LEFT JOIN refs r ON r.id = v.reference_id
    LEFT JOIN _dtc_concept_target_best ctb ON ctb.lin_rep = cl.original_permid
    WHERE ns.invalidates = true
      AND (v.evidence,
           COALESCE(COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int), -999999),
           v.id)
        > (cl.acc_ev, COALESCE(cl.acc_yr, -999999), cl.acc_id)
      AND (v.evidence,
           COALESCE(COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int), -999999),
           v.id)
        > (COALESCE(ctb.evidence, false), COALESCE(ctb.yr, -999999), COALESCE(ctb.opinion_id, -1));
    CREATE INDEX ON _dtc_lin_invalidated(lin_rep);
    ANALYZE _dtc_lin_invalidated;

    DROP TABLE IF EXISTS _dtc_con_all_invalidated;
    CREATE TEMP TABLE _dtc_con_all_invalidated AS
    SELECT c.con_rep
    FROM _dtc_con c
    GROUP BY c.con_rep
    HAVING bool_and(EXISTS (SELECT 1 FROM _dtc_lin_invalidated li WHERE li.lin_rep = c.lin_rep));
    CREATE INDEX ON _dtc_con_all_invalidated(con_rep);
    ANALYZE _dtc_con_all_invalidated;

    -- Concepts genuinely narrowed by the veto (some but not all members
    -- invalidated) -- see derive_taxa()'s _dtu_con_has_invalidated comment
    -- for why priority must be promoted ahead of the mechanical tiebreak for
    -- exactly these concepts, and no others.
    DROP TABLE IF EXISTS _dtc_con_has_invalidated;
    CREATE TEMP TABLE _dtc_con_has_invalidated AS
    SELECT DISTINCT c.con_rep
    FROM _dtc_con c
    JOIN _dtc_lin_invalidated li ON li.lin_rep = c.lin_rep
    WHERE c.con_rep NOT IN (SELECT con_rep FROM _dtc_con_all_invalidated);
    CREATE INDEX ON _dtc_con_has_invalidated(con_rep);
    ANALYZE _dtc_con_has_invalidated;

    -- ---- senior lineage per concept + concept_permid/rank -------------------
    -- Mirrors derive_taxa()'s/derive_linnaean()'s _dtu_conmeta/_dt_conmeta
    -- seniority tiebreak exactly, including the validity veto
    -- (fix-nomen-dubium-concept-seniority): a lineage never proposed junior
    -- to anything (con_sources) is preferred senior; ties break on the
    -- accepted spelling's own evidence/pubyr/id, then oldest original pubyr
    -- (promoted ahead of that mechanical tiebreak for concepts genuinely
    -- narrowed by the veto -- see _dtc_con_has_invalidated above), then
    -- lowest permid. con_sources drops an edge whose target is invalidated
    -- (unless the target's whole concept is all-invalidated) -- deferring to
    -- a lineage that can't win isn't a genuine deferral.
    DROP TABLE IF EXISTS _dtc_conmeta;
    CREATE TEMP TABLE _dtc_conmeta AS
    WITH con_sources AS MATERIALIZED (
        SELECT DISTINCT cw.jr
        FROM _dtc_con_winner cw
        JOIN _dtc_con c ON c.lin_rep = cw.jr
        WHERE cw.negates = false
          AND (
            c.con_rep IN (SELECT con_rep FROM _dtc_con_all_invalidated)
            OR NOT EXISTS (SELECT 1 FROM _dtc_lin_invalidated li WHERE li.lin_rep = cw.sr)
          )
    ),
    ranked AS MATERIALIZED (
        SELECT c.con_rep, c.lin_rep,
               row_number() OVER (PARTITION BY c.con_rep ORDER BY
                   (li.lin_rep IS NULL OR aic.con_rep IS NOT NULL) DESC,      -- validity exclusion
                   (cs.jr IS NULL) DESC,                                     -- (a) sink preference
                   CASE WHEN hic.con_rep IS NOT NULL THEN cl.original_yr END ASC NULLS LAST,  -- (c) promoted iff narrowed
                   cl.acc_ev DESC, cl.acc_yr DESC NULLS LAST, cl.acc_id DESC, -- (b) mechanical tiebreak
                   CASE WHEN hic.con_rep IS NULL THEN cl.original_yr END ASC NULLS LAST,      -- (c) original position otherwise
                   cl.original_permid ASC) AS rn                             -- (d)
        FROM _dtc_con c
        JOIN _dtc_lineage cl ON cl.original_permid = c.lin_rep
        LEFT JOIN con_sources cs ON cs.jr = c.lin_rep
        LEFT JOIN _dtc_lin_invalidated li ON li.lin_rep = c.lin_rep
        LEFT JOIN _dtc_con_all_invalidated aic ON aic.con_rep = c.con_rep
        LEFT JOIN _dtc_con_has_invalidated hic ON hic.con_rep = c.con_rep
    )
    SELECT r.con_rep, r.lin_rep AS senior_lin,
           cl.accepted_spelling_permid AS concept_permid,
           cl.accepted_rank_id AS concept_rank_id
    FROM ranked r
    JOIN _dtc_lineage cl ON cl.original_permid = r.lin_rep
    WHERE r.rn = 1;
    CREATE INDEX ON _dtc_conmeta(con_rep);
    ANALYZE _dtc_conmeta;

    -- ---- classification pooling + cycle-breaking loop -----------------------
    -- Mirrors derive_linnaean()'s _dt_assign: winning assignment pooled across the
    -- concept (senior lineage's own candidates always count; a junior lineage's
    -- candidate counts too when its own accepted rank equals the concept's -- the
    -- same equal-rank-borrowing shape as derive_linnaean(), minus the species
    -- exclusion, which has no analog among rank 24/25). Unlike _dt_assign's
    -- permissive LEFT JOINs (which tolerate an unresolvable container by just
    -- contributing NULL containment), the joins to _dtc_permid_lineage/_dtc_con
    -- here are INNER -- per spec, a candidate whose containing permid does not
    -- resolve to a clade lineage is not eligible at all (that cross-boundary case
    -- belongs to the separate clade_attachments pass, not here). Self-reference
    -- (the container resolving back to the subject's own concept) is excluded from
    -- the ranking contest entirely, same as _dt_assign. No rank-cardinality check:
    -- unranked/unranked clade both carry height IS NULL, so there is no
    -- finer/coarser ordering to check.
    --
    -- Because that structural firewall doesn't exist, genuine clade-to-clade
    -- containment cycles are resolved here instead of raised (unlike
    -- derive_linnaean(), which raises): confirmed against real pg_play data (5
    -- cycles, 11/2140 concepts -- see openspec/changes/derive-clade-attachments/).
    -- Each iteration rebuilds _dtc_assign/_dtc_node excluding whatever opinions
    -- prior iterations have cut, precisely identifies genuine cycle members (a
    -- concept whose own containment chain returns to ITSELF -- not merely any
    -- node downstream of a cycle, which would over-include; the same precise
    -- check derive_linnaean()'s own cycle guard uses, generalized here to return
    -- every such concept instead of just checking existence), and cuts the SINGLE
    -- weakest edge (lowest evidence/pubyr/id by the canonical order) among all
    -- current cycle members' own winning candidates. Repeats until no cycle
    -- remains.
    --
    -- Accepted caveat: cutting the globally-weakest edge can occasionally leave a
    -- directionally "backwards" placement on close evidence ties -- the same
    -- failure mode noted when a similar weakest-link approach was evaluated, and
    -- rejected, for derive_linnaean()'s own Hyriidae/Hyriinae cycle. It was rejected
    -- there only because a *better* alternative (rank-cardinality) existed and
    -- outperformed it; no such alternative exists for clades, so this is the best
    -- available option here, not a clean one -- a deliberate trade-off, not an
    -- oversight.
    DROP TABLE IF EXISTS _dtc_excluded_opinions;
    CREATE TEMP TABLE _dtc_excluded_opinions (
        opinion_id bigint PRIMARY KEY,
        concept_permid uuid,
        cycle_members uuid[]
    );

    <<cycle_break>>
    LOOP
        -- optimize-derive-taxa-cycle-loop: only the FIRST pass rebuilds
        -- _dtc_assign/_dtc_node from scratch. Every subsequent pass instead
        -- recomputes just the one con_rep whose previously-winning opinion
        -- was excluded by the PRIOR iteration's cut (affected_con_rep) --
        -- every other con_rep's candidate pool and ranking are provably
        -- unaffected by one more row in _dtc_excluded_opinions. See that
        -- change's design.md ("Why the single-con_rep recompute is safe").
        -- _dtc_cycle_members below is UNCHANGED and still re-verifies the
        -- whole graph every pass -- a replacement edge can introduce a path
        -- through arbitrary other parts of the graph, so global
        -- cycle re-detection is not something this optimization touches.
        IF affected_con_rep IS NULL THEN
            DROP TABLE IF EXISTS _dtc_assign;
            CREATE TEMP TABLE _dtc_assign AS
            WITH cand AS MATERIALIZED (
                SELECT cm.con_rep, a.id AS opinion_id, ccc.con_rep AS containing_con_rep,
                       a.evidence,
                       COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
                       -- Was this candidate filed on the concept's own senior lineage,
                       -- or only pooled in via the equal-rank-borrowing branch (e.g. a
                       -- junior synonym's own opinion, as with Iguanodontia getting
                       -- pooled into Ornithopoda's concept)? Used below to break
                       -- cycle-cut ties toward the borrowed candidate.
                       (sl.original_permid = cm.senior_lin) AS is_senior
                FROM assignment_opinions a
                JOIN _dtc_permid_lineage sl ON sl.permid = a.subject_permid
                JOIN _dtc_con sc ON sc.lin_rep = sl.original_permid
                JOIN _dtc_conmeta cm ON cm.con_rep = sc.con_rep
                JOIN _dtc_lineage cl ON cl.original_permid = sl.original_permid
                JOIN _dtc_permid_lineage ccl ON ccl.permid = a.containing_permid
                JOIN _dtc_con ccc ON ccc.lin_rep = ccl.original_permid
                LEFT JOIN refs r ON r.id = a.reference_id
                WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
                  AND ( sl.original_permid = cm.senior_lin
                        OR cl.accepted_rank_id = cm.concept_rank_id )
                  AND ccc.con_rep IS DISTINCT FROM cm.con_rep
                  AND NOT EXISTS (SELECT 1 FROM _dtc_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ),
            win AS MATERIALIZED (
                SELECT con_rep, opinion_id, containing_con_rep, evidence, yr, is_senior,
                       row_number() OVER (PARTITION BY con_rep
                           ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
                FROM cand
            )
            SELECT con_rep, opinion_id AS winning_assignment_opinion_id, containing_con_rep,
                   evidence, yr, is_senior
            FROM win WHERE rn = 1;
            CREATE INDEX ON _dtc_assign(con_rep);
            ANALYZE _dtc_assign;

            -- ---- per-concept node (concept_permid, containing_concept_permid) --
            DROP TABLE IF EXISTS _dtc_node;
            CREATE TEMP TABLE _dtc_node AS
            SELECT cm.con_rep, cm.concept_permid, cm.concept_rank_id,
                   ccm.concept_permid AS containing_concept_permid,
                   a.winning_assignment_opinion_id, a.evidence, a.yr, a.is_senior
            FROM _dtc_conmeta cm
            LEFT JOIN _dtc_assign a ON a.con_rep = cm.con_rep
            LEFT JOIN _dtc_conmeta ccm ON ccm.con_rep = a.containing_con_rep;
            CREATE INDEX ON _dtc_node(con_rep);
            CREATE INDEX ON _dtc_node(concept_permid);
            CREATE INDEX ON _dtc_node(containing_concept_permid);
            ANALYZE _dtc_node;
        ELSE
            -- Same cand logic as the full build above, scoped to the one
            -- affected con_rep and simplified accordingly (no PARTITION BY
            -- needed once already scoped to a single con_rep). containing_con_rep
            -- resolves directly here (unlike derive_taxa()/derive_linnaean()),
            -- since _dtc's cand CTE already joins through to it via INNER JOINs
            -- (both sides of a clade-to-clade edge must resolve as clade lineages).
            SELECT a.id, ccc.con_rep, a.evidence,
                   COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int),
                   (sl.original_permid = cm.senior_lin)
            INTO new_opinion_id, new_containing_con_rep, new_evidence, new_yr, new_is_senior
            FROM assignment_opinions a
            JOIN _dtc_permid_lineage sl ON sl.permid = a.subject_permid
            JOIN _dtc_con sc ON sc.lin_rep = sl.original_permid
            JOIN _dtc_conmeta cm ON cm.con_rep = sc.con_rep AND cm.con_rep = affected_con_rep
            JOIN _dtc_lineage cl ON cl.original_permid = sl.original_permid
            JOIN _dtc_permid_lineage ccl ON ccl.permid = a.containing_permid
            JOIN _dtc_con ccc ON ccc.lin_rep = ccl.original_permid
            LEFT JOIN refs r ON r.id = a.reference_id
            WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
              AND ( sl.original_permid = cm.senior_lin
                    OR cl.accepted_rank_id = cm.concept_rank_id )
              AND ccc.con_rep IS DISTINCT FROM cm.con_rep
              AND NOT EXISTS (SELECT 1 FROM _dtc_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ORDER BY a.evidence DESC,
                     COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                     a.id DESC
            LIMIT 1;

            IF new_opinion_id IS NOT NULL THEN
                UPDATE _dtc_assign SET
                    winning_assignment_opinion_id = new_opinion_id,
                    containing_con_rep = new_containing_con_rep,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;

                UPDATE _dtc_node SET
                    containing_concept_permid = (SELECT ccm.concept_permid FROM _dtc_conmeta ccm
                                                   WHERE ccm.con_rep = new_containing_con_rep),
                    winning_assignment_opinion_id = new_opinion_id,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;
            ELSE
                DELETE FROM _dtc_assign WHERE con_rep = affected_con_rep;

                UPDATE _dtc_node SET
                    containing_concept_permid = NULL, winning_assignment_opinion_id = NULL,
                    evidence = NULL, yr = NULL, is_senior = NULL
                WHERE con_rep = affected_con_rep;
            END IF;

            new_opinion_id := NULL;
            new_containing_con_rep := NULL;
            new_evidence := NULL;
            new_yr := NULL;
            new_is_senior := NULL;
            affected_con_rep := NULL;
        END IF;

        -- ---- cheap survivor set via iterative peeling (optimize-derive-taxa-
        -- cycle-loop) ------------------------------------------------------
        -- The walk below only needs to run from nodes that COULD be cycle
        -- members -- and a genuine cycle member's own container is always
        -- ANOTHER cycle member (the loop is mutually self-supporting), so it
        -- can never be pruned by "delete any node whose own container isn't
        -- itself still present." Survivors = every genuine cycle member plus
        -- everything permanently downstream of one; on real data this is a
        -- tiny fraction of the full node set, turning an O(V x 10000) walk
        -- from every node into one from just the survivors. Same algorithm
        -- derive_taxa() already uses for exactly this reason.
        DROP TABLE IF EXISTS _dtc_peel;
        CREATE TEMP TABLE _dtc_peel AS
        SELECT con_rep, concept_permid, containing_concept_permid
        FROM _dtc_node WHERE containing_concept_permid IS NOT NULL;
        CREATE INDEX ON _dtc_peel(concept_permid);
        CREATE INDEX ON _dtc_peel(con_rep);
        ANALYZE _dtc_peel;

        <<peel>>
        LOOP
            DELETE FROM _dtc_peel a
            WHERE NOT EXISTS (SELECT 1 FROM _dtc_peel b WHERE b.concept_permid = a.containing_concept_permid);
            GET DIAGNOSTICS peeled_count = ROW_COUNT;
            EXIT peel WHEN peeled_count = 0;
        END LOOP peel;

        -- genuine cycle members this round (a concept whose own containment
        -- chain returns to ITSELF), materialized so both the weakest-edge
        -- pick below and the audit log can reuse it. Sourced from _dtc_peel
        -- (survivors only) rather than _dtc_node -- identical result, since
        -- every genuine cycle member is provably a survivor, but the walk
        -- only has to consider the (usually far smaller) survivor set.
        DROP TABLE IF EXISTS _dtc_cycle_members;
        CREATE TEMP TABLE _dtc_cycle_members AS
        WITH RECURSIVE walk AS (
            SELECT con_rep AS start_rep, containing_concept_permid, 1 AS depth
            FROM _dtc_peel
            UNION ALL
            SELECT w.start_rep, n.containing_concept_permid, w.depth + 1
            FROM walk w
            JOIN _dtc_peel cn ON cn.concept_permid = w.containing_concept_permid
            JOIN _dtc_peel n  ON n.con_rep = cn.con_rep
            WHERE w.depth < 10000
        )
        SELECT DISTINCT w.start_rep AS con_rep
        FROM walk w
        JOIN _dtc_peel self ON self.con_rep = w.start_rep
        WHERE w.containing_concept_permid = self.concept_permid;

        -- find the weakest winning edge among this round's genuine cycle members
        -- (NULL if none remain). On an evidence/pubyr tie, prefer cutting an
        -- edge borrowed from a pooled/junior lineage (is_senior false) over one
        -- filed directly on the concept's own senior lineage (is_senior true) --
        -- a borrowed edge is more likely to be a synonym-pooling artifact than a
        -- real disagreement about the anchor name itself. Falls back to
        -- opinion_id (arbitrary, last resort) only when even that ties. See the
        -- Ornithopoda/Clypeodonta case in docs/clade-hierarchy-user-guide.html:
        -- the cycle there was created by Iguanodontia's own opinion being pooled
        -- into Ornithopoda's concept, not by Ornithopoda's and Clypeodonta's own
        -- opinions disagreeing. Also captures which con_rep that edge belongs
        -- to (affected_con_rep) -- optimize-derive-taxa-cycle-loop's
        -- incremental recompute on the next pass needs it.
        SELECT a.winning_assignment_opinion_id, a.con_rep INTO cut_opinion_id, affected_con_rep
        FROM _dtc_cycle_members cyc
        JOIN _dtc_node a ON a.con_rep = cyc.con_rep
        ORDER BY a.evidence ASC, a.yr ASC NULLS FIRST, a.is_senior ASC, a.winning_assignment_opinion_id ASC
        LIMIT 1;

        EXIT cycle_break WHEN cut_opinion_id IS NULL;

        INSERT INTO _dtc_excluded_opinions (opinion_id, concept_permid, cycle_members)
        SELECT cut_opinion_id,
               (SELECT nd.concept_permid FROM _dtc_node nd
                WHERE nd.winning_assignment_opinion_id = cut_opinion_id LIMIT 1),
               (SELECT array_agg(DISTINCT nd2.concept_permid)
                FROM _dtc_cycle_members cm2 JOIN _dtc_node nd2 ON nd2.con_rep = cm2.con_rep);
        cut_opinion_id := NULL;

        iter := iter + 1;
        IF iter > 1000 THEN
            RAISE EXCEPTION 'derive_taxa_clades: cycle-breaking loop did not converge after 1000 iterations';
        END IF;
    END LOOP cycle_break;

    -- ---- assembly: one row per minted clade permid, mirroring taxa_linnaean's
    -- own final assembly shape exactly. Every permid sharing a lineage/concept
    -- gets the SAME original_permid/accepted_spelling_permid/concept_permid/
    -- containing_concept_permid/winning_assignment_opinion_id (concept-level
    -- facts, repeated per row); name/rank_id/authority_id/
    -- nomenclatural_status_id/winning_name_opinion_id/
    -- winning_validity_opinion_id are each permid's OWN identity/validity,
    -- read fresh from `taxa_linnaean` -- not the lineage representative's.
    -- containing_concept_permid can still be NULL (rootless) when no
    -- eligible candidate exists (fewer than two clade lineages, no
    -- clade-to-clade containment opinion filed, the only candidate(s) were
    -- excluded as self-referential, or the cycle-breaking loop above cut
    -- this concept's only candidate).
    RETURN QUERY
    SELECT t2.permid,
           t2.name,
           t2.rank_id,
           t2.authority_id,
           pl.original_permid,
           cl.accepted_spelling_permid,
           nd.concept_permid,
           nd.containing_concept_permid,
           t2.nomenclatural_status_id,
           t2.winning_name_opinion_id,
           nd.winning_assignment_opinion_id,
           t2.winning_validity_opinion_id
    FROM _dtc_permid_lineage pl
    JOIN taxa_linnaean t2 ON t2.permid = pl.permid
    JOIN _dtc_lineage cl ON cl.original_permid = pl.original_permid
    JOIN _dtc_con c ON c.lin_rep = pl.original_permid
    JOIN _dtc_node nd ON nd.con_rep = c.con_rep
    WHERE permids IS NULL OR pl.permid = ANY(permids);
END;
$fn$;


-- ============================================================================
-- rebuild_taxa_clades() — cold path: derive(all) → upsert into the ledger
-- ============================================================================
CREATE OR REPLACE FUNCTION rebuild_taxa_clades()
RETURNS integer LANGUAGE plpgsql AS $fn$
DECLARE
    changed integer := 0;
    deleted integer := 0;
BEGIN
    -- Materialize derive_taxa_clades()'s output once, so the insert/update
    -- below and the orphan deletion further down both read the same
    -- snapshot instead of calling derive_taxa_clades(NULL) twice.
    DROP TABLE IF EXISTS _rebuild_taxa_clades_src;
    CREATE TEMP TABLE _rebuild_taxa_clades_src AS SELECT * FROM derive_taxa_clades(NULL);

    -- Insert a row for every permid in the snapshot; where the permid
    -- already has a row, update it in place. Same no-op-on-no-change pattern as
    -- rebuild_taxa().
    INSERT INTO taxa_clades (permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id)
    SELECT permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id
    FROM _rebuild_taxa_clades_src
    ON CONFLICT (permid) DO UPDATE SET
        name                          = EXCLUDED.name,
        rank_id                       = EXCLUDED.rank_id,
        authority_id                  = EXCLUDED.authority_id,
        original_permid               = EXCLUDED.original_permid,
        accepted_spelling_permid      = EXCLUDED.accepted_spelling_permid,
        concept_permid                = EXCLUDED.concept_permid,
        containing_concept_permid     = EXCLUDED.containing_concept_permid,
        nomenclatural_status_id       = EXCLUDED.nomenclatural_status_id,
        winning_name_opinion_id       = EXCLUDED.winning_name_opinion_id,
        winning_assignment_opinion_id = EXCLUDED.winning_assignment_opinion_id,
        winning_validity_opinion_id   = EXCLUDED.winning_validity_opinion_id
    WHERE taxa_clades.name                      IS DISTINCT FROM EXCLUDED.name
       OR taxa_clades.rank_id                   IS DISTINCT FROM EXCLUDED.rank_id
       OR taxa_clades.authority_id              IS DISTINCT FROM EXCLUDED.authority_id
       OR taxa_clades.original_permid           IS DISTINCT FROM EXCLUDED.original_permid
       OR taxa_clades.accepted_spelling_permid  IS DISTINCT FROM EXCLUDED.accepted_spelling_permid
       OR taxa_clades.concept_permid            IS DISTINCT FROM EXCLUDED.concept_permid
       OR taxa_clades.containing_concept_permid IS DISTINCT FROM EXCLUDED.containing_concept_permid
       OR taxa_clades.nomenclatural_status_id   IS DISTINCT FROM EXCLUDED.nomenclatural_status_id
       OR taxa_clades.winning_name_opinion_id       IS DISTINCT FROM EXCLUDED.winning_name_opinion_id
       OR taxa_clades.winning_assignment_opinion_id IS DISTINCT FROM EXCLUDED.winning_assignment_opinion_id
       OR taxa_clades.winning_validity_opinion_id   IS DISTINCT FROM EXCLUDED.winning_validity_opinion_id;
    GET DIAGNOSTICS changed = ROW_COUNT;

    -- Remove rows for permids no longer produced by derive_taxa_clades() --
    -- e.g. a lineage that lost its last remaining candidate, or was excluded
    -- by a rank/validity rule. The upsert above has no way to detect or
    -- handle this: ON CONFLICT only ever inserts/updates.
    DELETE FROM taxa_clades t
    WHERE NOT EXISTS (SELECT 1 FROM _rebuild_taxa_clades_src s WHERE s.permid = t.permid);
    GET DIAGNOSTICS deleted = ROW_COUNT;
    changed := changed + deleted;

    -- Snapshot this run's cuts (left behind in _dtc_excluded_opinions by the
    -- derive_taxa_clades() call above, in this same session) into the
    -- permanent log.
    DELETE FROM cycle_cuts WHERE source = 'taxa_clades';
    INSERT INTO cycle_cuts (source, concept_permid, cut_opinion_id, cycle_members)
    SELECT 'taxa_clades', concept_permid, opinion_id, cycle_members FROM _dtc_excluded_opinions;

    RETURN changed;
END;
$fn$;


-- ============================================================================
-- assert_taxa_clades_invariant() — derive(all) ≡ the current taxa_clades rows
-- ============================================================================
CREATE OR REPLACE FUNCTION assert_taxa_clades_invariant()
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
    bad integer;
BEGIN
    WITH d AS (SELECT * FROM derive_taxa_clades(NULL)),
    heads AS (SELECT * FROM taxa_clades),
    mism AS (
        SELECT COALESCE(d.permid, h.permid) AS permid FROM d
        FULL JOIN heads h ON h.permid = d.permid
        WHERE d.permid IS NULL OR h.permid IS NULL
           OR h.name IS DISTINCT FROM d.name
           OR h.rank_id IS DISTINCT FROM d.rank_id
           OR h.original_permid IS DISTINCT FROM d.original_permid
           OR h.accepted_spelling_permid IS DISTINCT FROM d.accepted_spelling_permid
           OR h.concept_permid IS DISTINCT FROM d.concept_permid
           OR h.containing_concept_permid IS DISTINCT FROM d.containing_concept_permid
           OR h.nomenclatural_status_id IS DISTINCT FROM d.nomenclatural_status_id
    )
    SELECT count(*) INTO bad FROM mism;
    IF bad > 0 THEN
        RAISE EXCEPTION 'assert_taxa_clades_invariant: % permid(s) diverge between derive_taxa_clades(all) and the current taxa_clades rows', bad;
    END IF;
END;
$fn$;


-- ============================================================================
-- taxa_attachments — cross-boundary containment between taxa_linnaean and taxa_clades
-- ============================================================================
-- Both `derive_linnaean()` and `derive_taxa_clades()` require a candidate edge's
-- subject and container to be on the SAME side of the ranked/unranked-clade
-- line -- any `assignment_opinions` row naming a container on the OTHER side
-- is excluded from both. `taxa_attachments` is exactly that discarded
-- evidence, resolved instead of thrown away. See
-- openspec/changes/derive-clade-attachments/{proposal,design}.md and
-- specs/clade-attachments/spec.md.
--
-- MANY-TO-MANY, unlike `taxa_linnaean.containing_concept_permid`/
-- `taxa_clades.containing_concept_permid` (both single-parent): a concept can
-- have independently-supported attachments to more than one target, so the
-- natural key is the (concept_permid, direction, attached_to_concept_permid)
-- triple, not concept_permid alone. `concept_permid`/`attached_to_concept_permid`
-- are plain permid pointers (into `taxa_linnaean` or `taxa_clades`, depending on
-- direction), not SQL foreign keys -- same convention as
-- taxa_linnaean.containing_concept_permid.
CREATE TABLE taxa_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_permid uuid NOT NULL,
    direction text NOT NULL CHECK (direction IN ('ranked-in-clade', 'clade-in-ranked')),
    attached_to_concept_permid uuid NOT NULL,
    winning_assignment_opinion_id bigint NOT NULL REFERENCES assignment_opinions("id"),
    created_at timestamptz DEFAULT NOW(),
    UNIQUE (concept_permid, direction, attached_to_concept_permid)
);

-- NOT versioned -- a plain cache, upserted in place by rebuild_clade_attachments()
-- (same pattern as `taxa_linnaean`/rebuild_linnaean()).


-- ============================================================================
-- derive_clade_attachments() — pure function computing cross-boundary edges
-- ============================================================================
CREATE OR REPLACE FUNCTION derive_clade_attachments(permids uuid[] DEFAULT NULL)
RETURNS TABLE (
    concept_permid uuid,
    direction text,
    attached_to_concept_permid uuid,
    winning_assignment_opinion_id bigint
) LANGUAGE plpgsql AS $fn$
#variable_conflict use_column
BEGIN
    -- ---- resolve any permid to its side + true concept identity ------------
    -- `taxa_linnaean` holds a row for every minted permid regardless of rank,
    -- so membership in `taxa_clades` (not merely a `taxa_linnaean` row's own
    -- concept grouping) is what identifies the clade side and its correctly
    -- clade-merged concept_permid.
    DROP TABLE IF EXISTS _dca_resolve;
    CREATE TEMP TABLE _dca_resolve AS
    SELECT t.permid,
           (tc.permid IS NOT NULL) AS is_clade,
           COALESCE(tc.concept_permid, t.concept_permid) AS concept_permid
    FROM taxa_linnaean t
    LEFT JOIN taxa_clades tc ON tc.permid = t.permid;
    CREATE UNIQUE INDEX ON _dca_resolve(permid);
    ANALYZE _dca_resolve;

    -- ---- candidate pool: cross-boundary assignment_opinions only -----------
    -- A row is a candidate iff subject and container resolve to opposite
    -- sides. Same-side rows are excluded entirely -- already handled (or
    -- already excluded) by derive_linnaean()'s/derive_taxa_clades()'s own
    -- classification pooling. Defensive same-concept exclusion (per spec:
    -- currently unreachable, since concept merging across the boundary is
    -- already excluded upstream, but filtered anyway).
    DROP TABLE IF EXISTS _dca_cand;
    CREATE TEMP TABLE _dca_cand AS
    SELECT a.id AS opinion_id,
           a.evidence,
           COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
           rs.concept_permid AS subject_concept,
           rc.concept_permid AS container_concept,
           CASE WHEN rs.is_clade THEN 'clade-in-ranked' ELSE 'ranked-in-clade' END AS direction
    FROM assignment_opinions a
    JOIN _dca_resolve rs ON rs.permid = a.subject_permid
    JOIN _dca_resolve rc ON rc.permid = a.containing_permid
    LEFT JOIN refs r ON r.id = a.reference_id
    WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
      AND rs.is_clade IS DISTINCT FROM rc.is_clade
      AND rs.concept_permid IS DISTINCT FROM rc.concept_permid
      AND (permids IS NULL OR a.subject_permid = ANY(permids) OR a.containing_permid = ANY(permids));
    CREATE INDEX ON _dca_cand(subject_concept, container_concept, direction);
    ANALYZE _dca_cand;

    -- ---- winner selection: scoped per (subject concept, target concept, --
    -- direction) pair, not per subject -- collapses repeated/superseded ------
    -- opinions about the SAME attachment, but keeps independently-supported --
    -- attachments to distinct targets (many-to-many, unlike
    -- taxa_linnaean.containing_concept_permid's single-parent shape).
    RETURN QUERY
    WITH win AS MATERIALIZED (
        SELECT subject_concept, container_concept, direction, opinion_id,
               row_number() OVER (PARTITION BY subject_concept, container_concept, direction
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM _dca_cand
    )
    SELECT subject_concept, direction, container_concept, opinion_id
    FROM win WHERE rn = 1;
END;
$fn$;


-- ============================================================================
-- rebuild_clade_attachments() — cold path: derive(all) → upsert into the ledger
-- ============================================================================
CREATE OR REPLACE FUNCTION rebuild_clade_attachments()
RETURNS integer LANGUAGE plpgsql AS $fn$
DECLARE
    changed integer := 0;
    deleted integer := 0;
BEGIN
    -- Materialize derive_clade_attachments()'s output once, so the
    -- insert/update below and the orphan deletion further down both read the
    -- same snapshot instead of calling derive_clade_attachments(NULL) twice.
    DROP TABLE IF EXISTS _rebuild_clade_attachments_src;
    CREATE TEMP TABLE _rebuild_clade_attachments_src AS SELECT * FROM derive_clade_attachments(NULL);

    -- Insert a row for every edge in the snapshot; where the edge already
    -- has a row (matched on the (concept_permid, direction,
    -- attached_to_concept_permid) triple, its natural key), update it in place.
    -- Same no-op-on-no-change pattern as rebuild_linnaean()/rebuild_taxa_clades().
    INSERT INTO taxa_attachments (concept_permid, direction, attached_to_concept_permid,
        winning_assignment_opinion_id)
    SELECT concept_permid, direction, attached_to_concept_permid, winning_assignment_opinion_id
    FROM _rebuild_clade_attachments_src
    ON CONFLICT (concept_permid, direction, attached_to_concept_permid) DO UPDATE SET
        winning_assignment_opinion_id = EXCLUDED.winning_assignment_opinion_id
    WHERE taxa_attachments.winning_assignment_opinion_id IS DISTINCT FROM EXCLUDED.winning_assignment_opinion_id;
    GET DIAGNOSTICS changed = ROW_COUNT;

    -- Remove edges no longer produced by derive_clade_attachments() -- e.g.
    -- the assignment opinion that supported a cross-boundary attachment was
    -- superseded or removed. The upsert above has no way to detect or
    -- handle this: ON CONFLICT only ever inserts/updates.
    DELETE FROM taxa_attachments t
    WHERE NOT EXISTS (
        SELECT 1 FROM _rebuild_clade_attachments_src s
        WHERE s.concept_permid = t.concept_permid
          AND s.direction = t.direction
          AND s.attached_to_concept_permid = t.attached_to_concept_permid
    );
    GET DIAGNOSTICS deleted = ROW_COUNT;
    changed := changed + deleted;

    RETURN changed;
END;
$fn$;


-- ============================================================================
-- assert_clade_attachments_invariant() — derive(all) ≡ the current ledger rows
-- ============================================================================
CREATE OR REPLACE FUNCTION assert_clade_attachments_invariant()
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
    bad integer;
BEGIN
    WITH d AS (SELECT * FROM derive_clade_attachments(NULL)),
    heads AS (SELECT * FROM taxa_attachments),
    mism AS (
        SELECT COALESCE(d.concept_permid, h.concept_permid) AS concept_permid,
               COALESCE(d.direction, h.direction) AS direction,
               COALESCE(d.attached_to_concept_permid, h.attached_to_concept_permid) AS attached_to_concept_permid
        FROM d
        FULL JOIN heads h ON h.concept_permid = d.concept_permid
            AND h.direction = d.direction
            AND h.attached_to_concept_permid = d.attached_to_concept_permid
        WHERE d.concept_permid IS NULL OR h.concept_permid IS NULL
           OR h.winning_assignment_opinion_id IS DISTINCT FROM d.winning_assignment_opinion_id
    )
    SELECT count(*) INTO bad FROM mism;
    IF bad > 0 THEN
        RAISE EXCEPTION 'assert_clade_attachments_invariant: % edge(s) diverge between derive_clade_attachments(all) and the current taxa_attachments rows', bad;
    END IF;
END;
$fn$;


-- ============================================================================
-- taxa — the primary, combined Linnaean+clade hierarchy
-- ============================================================================
-- The taxa-tables-rework change reunifies what derive_linnaean()/
-- derive_taxa_clades()/derive_clade_attachments() split apart: this table and
-- derive_taxa() resolve Linnaean and clade opinions together in one pass, with
-- no rank-based exclusion, producing a single classification tree spanning
-- both domains. `taxa_linnaean`, `taxa_clades`, and `taxa_attachments` remain
-- as independently-derived secondary tables -- this is a fourth, independent
-- derivation over the same Layer 1 opinions, not a view or composition over
-- the other three. See openspec/changes/taxa-tables-rework/{proposal,design}.md
-- and specs/taxa-unified/spec.md.
--
-- Same identity/classification/provenance column shape as `taxa_linnaean` --
-- see that table's own header comment above for the rationale behind each
-- column.
CREATE TABLE taxa (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permid uuid NOT NULL CHECK ((get_byte(uuid_send(permid), 6) >> 4) = 7),

    name text NOT NULL,
    rank_id integer REFERENCES dictionaries.taxonomy_ranks("id") NOT NULL,
    authority_id bigint REFERENCES authorities("id"),

    original_permid uuid NOT NULL,
    accepted_spelling_permid uuid NOT NULL,
    concept_permid uuid NOT NULL,

    containing_concept_permid uuid,        -- NULL = root
    classification_path ltree,             -- ltree of concept permids, root → node

    nomenclatural_status_id integer REFERENCES dictionaries.nomenclatural_statuses("id"),

    winning_name_opinion_id       bigint REFERENCES name_opinions("id"),
    winning_assignment_opinion_id bigint REFERENCES assignment_opinions("id"),
    winning_validity_opinion_id   bigint REFERENCES validity_opinions("id"),

    removed boolean,
    created_at timestamptz DEFAULT NOW(),

    UNIQUE (permid)
);

-- NOT versioned -- a plain cache, one row per permid, upserted in place by
-- rebuild_taxa(), same pattern as taxa_linnaean/rebuild_linnaean().
CREATE INDEX taxa_original_idx
    ON taxa (original_permid);
CREATE INDEX taxa_accepted_spelling_idx
    ON taxa (accepted_spelling_permid);
CREATE INDEX taxa_concept_idx
    ON taxa (concept_permid);
CREATE INDEX taxa_containing_idx
    ON taxa (containing_concept_permid);
-- No GiST index on classification_path, unlike taxa_linnaean's taxa_path_idx:
-- confirmed against real pg_play data that merged Linnaean+clade chains reach
-- depth 70 (vs ~15-20 for Linnaean alone), producing ltree values up to 2589
-- characters that a GiST index page cannot hold ("failed to add item to index
-- page"). The column itself is unaffected -- only the specialized index is
-- dropped. Ancestor/descendant queries over this combined hierarchy's deep
-- chains should walk containing_concept_permid recursively instead (the same
-- pattern this file's own cycle-detection code already uses), not rely on an
-- ltree containment index. See openspec/changes/taxa-tables-rework/design.md.
CREATE INDEX taxa_name_idx
    ON taxa (name);


-- ============================================================================
-- derive_taxa() — pure function computing the combined Linnaean+clade hierarchy
-- ============================================================================
-- Mirrors derive_linnaean()'s structure exactly (identity, lineage grouping,
-- validity, per-lineage eligibility/original/accepted-spelling, concept
-- grouping, classification pooling, cycle-breaking loop, classification_path)
-- but drops every rank-based exclusion derive_linnaean() applies during
-- concept-grouping and classification-pooling: a candidate edge is eligible
-- regardless of whether either endpoint is Linnaean-ranked, unranked, or
-- unranked clade. This is what actually reunifies the two domains -- see
-- openspec/changes/taxa-tables-rework/design.md decision 2.
--
-- The one exclusion this function KEEPS from classification pooling is the
-- rank-cardinality/inversion check (a container SHALL NOT be more finely
-- ranked than what it contains) -- but unlike derive_linnaean()'s version,
-- which compares dictionaries.taxonomy_ranks.id directly (only safe there
-- because it never evaluates a candidate touching unranked/unranked clade,
-- excluded upstream by a separate filter this function doesn't have), this
-- function compares taxonomy_ranks.height, which is NULL for unranked/
-- unranked clade and NULL-safe by construction: either side having a NULL
-- height means "no comparison possible," so the candidate is NOT excluded --
-- unranked lineages are their own cardinality tier the inversion check simply
-- doesn't apply to, the same reasoning derive_taxa_clades() already documents
-- for why IT has no rank-cardinality check at all.
--
-- Never raises merely because a containment cycle was found -- only if the
-- cycle-breaking loop fails to converge after 1000 iterations, same as
-- derive_linnaean() and derive_taxa_clades().
--
-- optimize-derive-taxa-seed: `seed IS NOT NULL` takes a materially different
-- code path from `seed IS NULL` (which is the full, unscoped algorithm
-- described above, unchanged). Live profiling found `seed`'s original
-- implementation gave essentially no speedup (~1.12x) because it only
-- filtered the FINAL result rows -- every intermediate table, including the
-- classification cycle-breaking loop, was still built over the entire
-- ~500K-concept graph regardless of `seed` size, and that loop alone
-- accounted for ~90% of total runtime. For `seed IS NOT NULL`, this function
-- instead walks upward from each seed permid's own con_rep via
-- containing_concept_permid, resolving each con_rep's winning assignment on
-- demand (never building a bulk _dtu_assign/_dtu_node table) and cutting a
-- local cycle's weakest edge in place if the walk ever revisits an
-- already-visited con_rep -- see this change's design.md for the full
-- algorithm and the correctness argument (a con_rep's own winning candidate
-- never depends on any other con_rep's resolution order, so resolving lazily
-- along just the seed's own ancestry converges to the same answer a full
-- derive_taxa(NULL) call would give for that con_rep). Typical result: ~318s
-- down to ~13s for a single-permid seed.
CREATE OR REPLACE FUNCTION derive_taxa(seed uuid[] DEFAULT NULL)
RETURNS TABLE (
    permid uuid,
    name text,
    rank_id integer,
    authority_id bigint,
    original_permid uuid,
    accepted_spelling_permid uuid,
    concept_permid uuid,
    containing_concept_permid uuid,
    classification_path ltree,
    nomenclatural_status_id integer,
    winning_name_opinion_id bigint,
    winning_assignment_opinion_id bigint,
    winning_validity_opinion_id bigint
) LANGUAGE plpgsql AS $fn$
#variable_conflict use_column
DECLARE
    cut_opinion_id bigint;
    iter integer := 0;
    peeled_count integer;
    walk_con_rep uuid;
    walk_concept_permid uuid;
    walk_containing_permid uuid;
    walk_step integer;
    cycle_start_step integer;
    -- optimize-derive-taxa-cycle-loop: incremental _dtu_assign/_dtu_node
    -- recompute after the first loop pass (see that change's design.md).
    affected_con_rep uuid;
    new_opinion_id bigint;
    new_containing_permid uuid;
    new_containing_con_rep uuid;
    new_evidence boolean;
    new_yr integer;
    new_is_senior boolean;
    -- optimize-derive-taxa-seed: per-seed upward walk used instead of the
    -- above for seed IS NOT NULL (see that change's design.md, Decision 1).
    -- Prefixed swalk_ throughout, distinct from the walk_*/new_* variables
    -- above, which stay reserved for the seed IS NULL path.
    swalk_con_rep uuid;
    swalk_seed_con_rep uuid;
    swalk_cached boolean;
    swalk_step integer;
    swalk_cycle_start_step integer;
    swalk_cut_opinion_id bigint;
    swalk_iter integer;
    swalk_concept_permid uuid;
    swalk_concept_rank_id integer;
    swalk_new_opinion_id bigint;
    swalk_new_containing_permid uuid;
    swalk_new_containing_con_rep uuid;
    swalk_new_containing_concept_permid uuid;
    swalk_new_evidence boolean;
    swalk_new_yr integer;
    swalk_new_is_senior boolean;
BEGIN
    -- ---- identity: one row per minted permid, from its own root row only ---
    DROP TABLE IF EXISTS _dtu_identity;
    CREATE TEMP TABLE _dtu_identity AS
    SELECT n.subject_permid AS permid, n.id AS opinion_id, n.new_name, n.rank_id, n.authority_id
    FROM name_opinions n
    WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
      AND n.edge_class = 'root';
    CREATE INDEX ON _dtu_identity(permid);
    ANALYZE _dtu_identity;

    IF EXISTS (SELECT 1 FROM _dtu_identity GROUP BY permid HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'derive_taxa: permid % has more than one live root row (identity re-minted)',
            (SELECT permid FROM _dtu_identity GROUP BY permid HAVING count(*) > 1 LIMIT 1);
    END IF;

    -- ---- candidate introducing edges: one row per (permid, opinion) --------
    DROP TABLE IF EXISTS _dtu_edge_cand;
    CREATE TEMP TABLE _dtu_edge_cand AS
    SELECT n.subject_permid AS permid, n.id AS opinion_id, n.edge_class, n.target_permid,
           n.evidence,
           COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
           nr.never_accepted, n.negates
    FROM name_opinions n
    JOIN dictionaries.namechange_reasons nr ON nr.id = n.reason_id
    LEFT JOIN refs r ON r.id = n.reference_id
    WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
      AND n.edge_class IN ('root','name');
    CREATE INDEX ON _dtu_edge_cand(permid);
    ANALYZE _dtu_edge_cand;

    -- each permid's own canonical introducing edge (root or lineage, whichever
    -- ranks highest) -- feeds eligibility (below), never union-find membership.
    DROP TABLE IF EXISTS _dtu_permid_edge;
    CREATE TEMP TABLE _dtu_permid_edge AS
    WITH ranked AS MATERIALIZED (
        SELECT permid, opinion_id, evidence, yr, never_accepted,
               row_number() OVER (PARTITION BY permid
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM _dtu_edge_cand
        WHERE negates = false
    )
    SELECT permid, opinion_id, evidence, yr, never_accepted FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dtu_permid_edge(permid);
    ANALYZE _dtu_permid_edge;

    -- each subject's own top-ranked LINEAGE-class opinion only
    DROP TABLE IF EXISTS _dtu_lin_winner;
    CREATE TEMP TABLE _dtu_lin_winner AS
    WITH ranked AS MATERIALIZED (
        SELECT permid, target_permid, negates,
               row_number() OVER (PARTITION BY permid
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM _dtu_edge_cand
        WHERE edge_class = 'name'
    )
    SELECT permid, target_permid, negates FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dtu_lin_winner(permid);
    ANALYZE _dtu_lin_winner;

    -- ---- lineage union-find -------------------------------------------------
    DROP TABLE IF EXISTS _dtu_lin;
    CREATE TEMP TABLE _dtu_lin AS
    WITH RECURSIVE
    lin_undir AS MATERIALIZED (
        SELECT permid AS a, target_permid AS b FROM _dtu_lin_winner WHERE negates = false
        UNION
        SELECT target_permid, permid FROM _dtu_lin_winner WHERE negates = false
    ),
    reach(src, node) AS (
        SELECT permid, permid FROM _dtu_identity
        UNION
        SELECT r.src, u.b FROM reach r JOIN lin_undir u ON u.a = r.node
    )
    SELECT src AS permid, min(node::text)::uuid AS lin_rep FROM reach GROUP BY src;
    CREATE INDEX ON _dtu_lin(permid);
    CREATE INDEX ON _dtu_lin(lin_rep);
    ANALYZE _dtu_lin;

    -- ---- best concept-class opinion targeting each lineage -----------------
    -- Counter-signal for the validity veto below (both the lineage-level
    -- accepted-spelling contest and the concept-level senior contest): if
    -- some other name currently, evidently defers to this lineage via an
    -- ordinary synonymy opinion, that is itself proof the name was treated
    -- as legitimate after any invalidating validity ruling, even though
    -- nobody filed a formal "not dubious anymore" opinion (validity_opinions
    -- has no way to positively record a reversal -- see
    -- openspec/changes/fix-nomen-dubium-concept-seniority). Computed here,
    -- right after the lineage union-find, so both veto loops below can share
    -- it without a circular dependency on _dtu_linmeta.
    DROP TABLE IF EXISTS _dtu_concept_target_best;
    CREATE TEMP TABLE _dtu_concept_target_best AS
    WITH cand AS MATERIALIZED (
        SELECT lt.lin_rep,
               n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id,
               row_number() OVER (PARTITION BY lt.lin_rep
                   ORDER BY n.evidence DESC,
                            COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                            n.id DESC) AS rn
        FROM name_opinions n
        JOIN _dtu_lin lt ON lt.permid = n.target_permid
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL
          AND n.edge_class = 'concept' AND n.negates = false
    )
    SELECT lin_rep, evidence, yr, opinion_id FROM cand WHERE rn = 1;
    CREATE INDEX ON _dtu_concept_target_best(lin_rep);
    ANALYZE _dtu_concept_target_best;

    -- ---- validity per permid (moved up: eligibility below depends on it) ---
    DROP TABLE IF EXISTS _dtu_valid;
    CREATE TEMP TABLE _dtu_valid AS
    WITH cand AS MATERIALIZED (
        SELECT v.subject_permid AS permid, v.nomenclatural_status_id, v.id AS opinion_id,
               v.evidence,
               COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               ns.invalidates,
               row_number() OVER (PARTITION BY v.subject_permid
                   ORDER BY v.evidence DESC,
                            COALESCE(v.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                            v.id DESC) AS rn
        FROM validity_opinions v
        JOIN dictionaries.nomenclatural_statuses ns ON ns.id = v.nomenclatural_status_id
        LEFT JOIN refs r ON r.id = v.reference_id
        WHERE v.removed IS NOT TRUE AND v.succeeded_by_id IS NULL
    )
    SELECT permid, nomenclatural_status_id, opinion_id AS winning_validity_opinion_id,
           evidence, yr, invalidates
    FROM cand WHERE rn = 1;
    CREATE INDEX ON _dtu_valid(permid);
    ANALYZE _dtu_valid;

    -- ---- validity veto: which permids are actually invalidated -------------
    -- (fix-nomen-dubium-concept-seniority) A permid whose winning validity
    -- opinion has invalidates = true (nomen dubium/nomen nudum/nomen vanum)
    -- is NOT automatically excluded -- it is excluded only if that opinion's
    -- own rating (evidence/yr/id) outranks the best of (a) its own canonical
    -- introducing edge and (b) any live concept-class opinion naming its
    -- lineage as target (_dtu_concept_target_best). This determination is
    -- entirely static -- it never depends on who wins any ranking contest --
    -- so it is computed once, up front, not reactively inside a loop: an
    -- earlier version of this fix tried a provisional-winner/evict/rerun
    -- loop (mirroring the classification cycle-breaking loop below), but
    -- that only ever inspects whichever candidate is CURRENTLY winning --
    -- if an already-non-invalidated candidate wins the ranking purely
    -- because ITS competitors' disqualifying edges target an invalidated
    -- lineage (the actual Triceratops/Agathaumas shape), the invalidated
    -- lineage is never even examined. The exclusion has to be known before
    -- ranking runs, not discovered after.
    DROP TABLE IF EXISTS _dtu_permid_invalidated;
    CREATE TEMP TABLE _dtu_permid_invalidated AS
    SELECT pe.permid
    FROM _dtu_permid_edge pe
    JOIN _dtu_lin l ON l.permid = pe.permid
    JOIN _dtu_valid dv ON dv.permid = pe.permid
    LEFT JOIN _dtu_concept_target_best ctb ON ctb.lin_rep = l.lin_rep
    WHERE dv.invalidates = true
      AND (dv.evidence, COALESCE(dv.yr, -999999), dv.winning_validity_opinion_id)
          > (pe.evidence, COALESCE(pe.yr, -999999), pe.opinion_id)
      AND (dv.evidence, COALESCE(dv.yr, -999999), dv.winning_validity_opinion_id)
          > (COALESCE(ctb.evidence, false), COALESCE(ctb.yr, -999999), COALESCE(ctb.opinion_id, -1));
    CREATE INDEX ON _dtu_permid_invalidated(permid);
    ANALYZE _dtu_permid_invalidated;

    -- lineages where EVERY never_accepted-eligible permid is invalidated --
    -- the escape hatch: a lineage is never excluded down to zero candidates,
    -- so when this holds, the exclusion below is skipped for that lineage
    -- entirely and every member competes on the ordinary evidence/yr/id
    -- ranking as if none were invalidated.
    DROP TABLE IF EXISTS _dtu_lin_all_invalidated;
    CREATE TEMP TABLE _dtu_lin_all_invalidated AS
    SELECT l.lin_rep
    FROM _dtu_lin l
    JOIN _dtu_permid_edge pe ON pe.permid = l.permid
    WHERE pe.never_accepted = false
    GROUP BY l.lin_rep
    HAVING bool_and(EXISTS (SELECT 1 FROM _dtu_permid_invalidated pi WHERE pi.permid = l.permid));
    CREATE INDEX ON _dtu_lin_all_invalidated(lin_rep);
    ANALYZE _dtu_lin_all_invalidated;

    -- ---- per-lineage: eligibility, topological original_permid, accepted --
    -- spelling, and this lineage's accepted rank's height (NULL for
    -- unranked/unranked clade -- feeds the classification-pooling inversion
    -- check below) ------------------------------------------------------------
    DROP TABLE IF EXISTS _dtu_linmeta;
    CREATE TEMP TABLE _dtu_linmeta AS
    WITH
    eligible AS MATERIALIZED (
        SELECT pe.permid, pe.evidence, pe.yr, pe.opinion_id
        FROM _dtu_permid_edge pe
        JOIN _dtu_lin l ON l.permid = pe.permid
        WHERE pe.never_accepted = false
          AND (
            NOT EXISTS (SELECT 1 FROM _dtu_permid_invalidated pi WHERE pi.permid = pe.permid)
            OR EXISTS (SELECT 1 FROM _dtu_lin_all_invalidated ai WHERE ai.lin_rep = l.lin_rep)
          )
    ),
    sinks AS MATERIALIZED (
        SELECT l.lin_rep, l.permid
        FROM _dtu_lin l
        WHERE NOT EXISTS (
            SELECT 1 FROM _dtu_lin_winner w
            WHERE w.negates = false AND w.permid = l.permid
        )
    ),
    sink_counts AS MATERIALIZED (
        SELECT lin_rep, count(*) AS n FROM sinks GROUP BY lin_rep
    ),
    roots AS MATERIALIZED (
        SELECT sc.lin_rep, s.permid AS original_permid
        FROM sink_counts sc JOIN sinks s ON s.lin_rep = sc.lin_rep
        WHERE sc.n = 1
        UNION ALL
        SELECT sc.lin_rep,
               (array_agg(cand.permid ORDER BY cand.evidence DESC, cand.yr DESC NULLS LAST,
                          cand.opinion_id DESC, cand.permid))[1]
        FROM sink_counts sc
        JOIN LATERAL (
            SELECT pe.permid, pe.evidence, pe.yr, pe.opinion_id
            FROM (SELECT permid FROM sinks WHERE lin_rep = sc.lin_rep
                  UNION ALL
                  SELECT l.permid FROM _dtu_lin l WHERE l.lin_rep = sc.lin_rep AND sc.n = 0) c
            JOIN _dtu_permid_edge pe ON pe.permid = c.permid
        ) cand ON true
        WHERE sc.n != 1
        GROUP BY sc.lin_rep
    ),
    spelling AS MATERIALIZED (
        SELECT l.lin_rep, e.permid, di.rank_id,
               row_number() OVER (PARTITION BY l.lin_rep
                   ORDER BY e.evidence DESC, e.yr DESC NULLS LAST, e.opinion_id DESC) AS rn,
               e.evidence AS acc_ev, e.yr AS acc_yr, e.opinion_id AS acc_id
        FROM _dtu_lin l
        JOIN eligible e ON e.permid = l.permid
        JOIN _dtu_identity di ON di.permid = e.permid
    )
    SELECT s.lin_rep,
           r.original_permid,
           s.permid AS accepted_spelling_permid,
           s.rank_id AS accepted_rank_id,
           tr.height AS accepted_rank_height,
           s.acc_ev, s.acc_yr, s.acc_id,
           (SELECT COALESCE(pe2.yr, 999999) FROM _dtu_permid_edge pe2
             WHERE pe2.permid = r.original_permid) AS original_yr
    FROM spelling s
    JOIN roots r ON r.lin_rep = s.lin_rep
    JOIN dictionaries.taxonomy_ranks tr ON tr.id = s.rank_id
    WHERE s.rn = 1;
    CREATE INDEX ON _dtu_linmeta(lin_rep);
    ANALYZE _dtu_linmeta;

    -- each lineage's own top-ranked CONCEPT-class opinion, pooled across all
    -- of that lineage's member permids. Unlike derive_linnaean(), NO exclusion
    -- on either side's accepted rank: a candidate touching an unranked/
    -- unranked-clade lineage is fully eligible here -- this is what reunifies
    -- Linnaean and clade synonymy into one union-find.
    DROP TABLE IF EXISTS _dtu_con_winner;
    CREATE TEMP TABLE _dtu_con_winner AS
    WITH cand AS MATERIALIZED (
        SELECT ls.lin_rep AS jr, lt.lin_rep AS sr, n.evidence,
               COALESCE(n.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
               n.id AS opinion_id, n.negates
        FROM name_opinions n
        JOIN _dtu_lin ls ON ls.permid = n.subject_permid
        JOIN _dtu_lin lt ON lt.permid = n.target_permid
        LEFT JOIN refs r ON r.id = n.reference_id
        WHERE n.removed IS NOT TRUE AND n.succeeded_by_id IS NULL AND n.edge_class = 'concept'
    ),
    ranked AS MATERIALIZED (
        SELECT jr, sr, negates,
               row_number() OVER (PARTITION BY jr
                   ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
        FROM cand
    )
    SELECT jr, sr, negates FROM ranked WHERE rn = 1;
    CREATE INDEX ON _dtu_con_winner(jr);
    ANALYZE _dtu_con_winner;

    -- ---- concept union-find -------------------------------------------------
    DROP TABLE IF EXISTS _dtu_con;
    CREATE TEMP TABLE _dtu_con AS
    WITH RECURSIVE
    con_edge AS MATERIALIZED (
        SELECT jr, sr FROM _dtu_con_winner WHERE negates = false
    ),
    con_undir AS MATERIALIZED (
        SELECT jr AS a, sr AS b FROM con_edge UNION SELECT sr, jr FROM con_edge
    ),
    reach(src, node) AS (
        SELECT DISTINCT lin_rep, lin_rep FROM _dtu_lin
        UNION
        SELECT r.src, u.b FROM reach r JOIN con_undir u ON u.a = r.node
    )
    SELECT src AS lin_rep, min(node::text)::uuid AS con_rep FROM reach GROUP BY src;
    CREATE INDEX ON _dtu_con(lin_rep);
    CREATE INDEX ON _dtu_con(con_rep);
    ANALYZE _dtu_con;

    -- ---- validity veto: which lineages are excluded from concept seniority -
    -- (fix-nomen-dubium-concept-seniority) A lineage whose accepted-spelling
    -- permid is invalidated (_dtu_permid_invalidated above) cannot win a
    -- concept's senior-representative role, unless every candidate lineage
    -- in the concept is invalidated (the same escape hatch as the lineage-
    -- level veto: never exclude a concept down to zero senior candidates).
    -- Static and non-iterative for the same reason as the lineage-level
    -- veto above -- it never depends on who wins any ranking contest.
    DROP TABLE IF EXISTS _dtu_lin_invalidated;
    CREATE TEMP TABLE _dtu_lin_invalidated AS
    SELECT lm.lin_rep
    FROM _dtu_linmeta lm
    WHERE EXISTS (SELECT 1 FROM _dtu_permid_invalidated pi WHERE pi.permid = lm.accepted_spelling_permid);
    CREATE INDEX ON _dtu_lin_invalidated(lin_rep);
    ANALYZE _dtu_lin_invalidated;

    DROP TABLE IF EXISTS _dtu_con_all_invalidated;
    CREATE TEMP TABLE _dtu_con_all_invalidated AS
    SELECT c.con_rep
    FROM _dtu_con c
    GROUP BY c.con_rep
    HAVING bool_and(EXISTS (SELECT 1 FROM _dtu_lin_invalidated li WHERE li.lin_rep = c.lin_rep));
    CREATE INDEX ON _dtu_con_all_invalidated(con_rep);
    ANALYZE _dtu_con_all_invalidated;

    -- Concepts where SOME but not all members are invalidated: the only
    -- concepts whose senior-candidate pool is actually narrowed by validity
    -- considerations. Excluding an invalid competitor (e.g. Agathaumas, a
    -- nomen dubium) from a synonymy group commonly leaves the SURVIVORS
    -- (e.g. Triceratops, Avaceratops, Brachyceratops -- none individually
    -- disqualified by anything else) tied on sink preference, with nothing
    -- left to break the tie but the mechanical acc_ev/acc_yr/acc_id order --
    -- which is exactly the same recency bias that produced the original
    -- Triceratops/Tatankaceratops bug one level up (that field measures a
    -- lineage's own spelling-acceptance confidence, not group seniority).
    -- For THESE concepts only, nomenclatural priority (original_yr) is
    -- promoted ahead of that mechanical tiebreak in the ranked CTE below --
    -- matching ICZN Article 23.1's actual default when nothing else
    -- distinguishes the survivors. Concepts with NO invalidated member
    -- (e.g. Cathartidae/Vulturidae, a real evidenced determination with no
    -- validity status involved at all) keep the ORIGINAL, unmodified
    -- (a)-(d) order -- promoting priority universally was tried and
    -- rejected earlier in this fix's development precisely because it
    -- overturned real evidenced calls like that one.
    DROP TABLE IF EXISTS _dtu_con_has_invalidated;
    CREATE TEMP TABLE _dtu_con_has_invalidated AS
    SELECT DISTINCT c.con_rep
    FROM _dtu_con c
    JOIN _dtu_lin_invalidated li ON li.lin_rep = c.lin_rep
    WHERE c.con_rep NOT IN (SELECT con_rep FROM _dtu_con_all_invalidated);
    CREATE INDEX ON _dtu_con_has_invalidated(con_rep);
    ANALYZE _dtu_con_has_invalidated;

    -- senior lineage per concept + concept_permid/rank. con_sources drops an
    -- edge whose target is invalidated (unless the target's whole concept is
    -- all-invalidated) -- deferring to a lineage that can't win isn't a
    -- genuine deferral. The ranked CTE's ORDER BY is criteria (a)-(d) from
    -- before this fix, with priority conditionally promoted per the
    -- _dtu_con_has_invalidated comment above.
    DROP TABLE IF EXISTS _dtu_conmeta;
    CREATE TEMP TABLE _dtu_conmeta AS
    WITH con_sources AS MATERIALIZED (
        SELECT DISTINCT cw.jr
        FROM _dtu_con_winner cw
        JOIN _dtu_con c ON c.lin_rep = cw.jr
        WHERE cw.negates = false
          AND (
            c.con_rep IN (SELECT con_rep FROM _dtu_con_all_invalidated)
            OR NOT EXISTS (SELECT 1 FROM _dtu_lin_invalidated li WHERE li.lin_rep = cw.sr)
          )
    ),
    ranked AS MATERIALIZED (
        SELECT c.con_rep, c.lin_rep,
               row_number() OVER (PARTITION BY c.con_rep ORDER BY
                   (li.lin_rep IS NULL OR aic.con_rep IS NOT NULL) DESC,      -- validity exclusion
                   (cs.jr IS NULL) DESC,                                     -- (a) sink preference
                   CASE WHEN hic.con_rep IS NOT NULL THEN lm.original_yr END ASC NULLS LAST,  -- (c) promoted here iff narrowed by validity
                   lm.acc_ev DESC, lm.acc_yr DESC NULLS LAST, lm.acc_id DESC, -- (b) mechanical tiebreak
                   CASE WHEN hic.con_rep IS NULL THEN lm.original_yr END ASC NULLS LAST,      -- (c) original position otherwise
                   lm.original_permid ASC) AS rn                             -- (d)
        FROM _dtu_con c
        JOIN _dtu_linmeta lm ON lm.lin_rep = c.lin_rep
        LEFT JOIN con_sources cs ON cs.jr = c.lin_rep
        LEFT JOIN _dtu_lin_invalidated li ON li.lin_rep = c.lin_rep
        LEFT JOIN _dtu_con_all_invalidated aic ON aic.con_rep = c.con_rep
        LEFT JOIN _dtu_con_has_invalidated hic ON hic.con_rep = c.con_rep
    )
    SELECT r.con_rep, r.lin_rep AS senior_lin,
           lm.accepted_spelling_permid AS concept_permid,
           lm.accepted_rank_id AS concept_rank_id,
           tr.taxonomy_rank AS concept_rank_name
    FROM ranked r
    JOIN _dtu_linmeta lm ON lm.lin_rep = r.lin_rep
    JOIN dictionaries.taxonomy_ranks tr ON tr.id = lm.accepted_rank_id
    WHERE r.rn = 1;
    CREATE INDEX ON _dtu_conmeta(con_rep);
    ANALYZE _dtu_conmeta;

    -- ---- classification: winning assignment pooled across the concept ------
    -- Self-referential candidates excluded before ranking, same as
    -- derive_linnaean(). NO unranked-lineage exclusion here (unlike
    -- derive_linnaean()): a concept accepted at unranked/unranked clade CAN be
    -- assigned a containing_concept_permid, and CAN serve as another concept's
    -- container -- this is what lets cross-boundary containment resolve here
    -- instead of being diverted to derive_clade_attachments(). The rank-
    -- cardinality/inversion check IS kept, but height-based and NULL-safe --
    -- see this function's own header comment.
    --
    -- ---- classification cycle-breaking loop --------------------------------
    -- Merging two previously-separated domains reopens cycle shapes neither
    -- derive_linnaean() nor derive_taxa_clades() had to handle alone -- see
    -- openspec/changes/taxa-tables-rework/design.md decision 4. Confirmed
    -- against real pg_play data: dropping the rank-based containment
    -- exclusions surfaces a genuine, tiny (3-concept) cycle among basal
    -- unranked clades (Eukarya/Proepitheliozoa/Euradiculata) sitting at the
    -- root of the entire eukaryote subtree -- so unlike every previously
    -- known cycle in this codebase (always small AND deep in the tree), this
    -- one is small but sits at the ROOT of a subtree with ~283K descendants.
    --
    -- derive_linnaean()'s/derive_taxa_clades()'s cycle-member detection --
    -- walk from EVERY non-root node up to depth 10000, checking for a
    -- self-revisit -- costs nothing extra when a broken cycle is deep/local
    -- (their only real-world cases so far), but is catastrophic here: with
    -- ~283K nodes all funneling through the same 3-node cycle near the root,
    -- that walk performs on the order of 283K * 10000 row explorations before
    -- ever finding the cycle. This function uses a different algorithm for
    -- exactly that reason -- iterative peeling (Kahn's algorithm run in
    -- reverse), the same approach already prototyped in
    -- migration_exploration/testing/find-containment-cycle.js for this exact
    -- problem: repeatedly delete any node whose own parent is not itself
    -- still present. What survives to a fixed point is precisely "cycle
    -- members plus everything permanently downstream of one" -- O(V) per
    -- round, no per-node bounded walk. A single arbitrary walk from one
    -- survivor is then enough to isolate the actual cycle within that
    -- (usually much smaller) survivor set: since every survivor's parent is
    -- also a survivor by the peeling invariant, that walk is guaranteed to
    -- hit a repeat, and the repeated sub-path IS the cycle -- no per-node
    -- walk over the full node set is ever needed.
    --
    -- This only ever isolates and cuts ONE cycle's weakest edge per
    -- iteration (not the global weakest across every simultaneously-existing
    -- cycle, unlike derive_linnaean()'s/derive_taxa_clades()'s walk, which
    -- finds all cycle members at once). If multiple genuinely disjoint
    -- cycles exist, this simply takes one additional iteration per extra
    -- cycle -- correct either way, since the loop already rebuilds from
    -- scratch and re-checks every iteration; only which edge gets cut first
    -- when several unrelated cycles coexist can differ, and the "weakest
    -- edge" cut was already a documented heuristic, not a global optimum.
    DROP TABLE IF EXISTS _dtu_excluded_opinions;
    CREATE TEMP TABLE _dtu_excluded_opinions (
        opinion_id bigint PRIMARY KEY,
        concept_permid uuid,
        cycle_members uuid[]
    );

    -- optimize-derive-taxa-seed: seed IS NULL keeps the global cycle-breaking
    -- loop and full-tree classification_path build below exactly as before
    -- (see this change's design.md, Non-Goals: that path is untouched). For
    -- seed IS NOT NULL, the ELSE branch (after this whole loop) replaces
    -- both with an on-demand upward walk scoped to just the con_reps
    -- reachable from the requested permids, never building _dtu_assign or a
    -- full _dtu_node/_dtu_path at all.
    IF seed IS NULL THEN

    <<cycle_break>>
    LOOP
        -- optimize-derive-taxa-cycle-loop: only the FIRST pass rebuilds
        -- _dtu_assign/_dtu_node from scratch. Every subsequent pass instead
        -- recomputes just the one con_rep whose previously-winning opinion
        -- was excluded by the PRIOR iteration's cut (affected_con_rep) --
        -- every other con_rep's candidate pool and ranking are provably
        -- unaffected by one more row in _dtu_excluded_opinions. See that
        -- change's design.md ("Why the single-con_rep recompute is safe").
        -- _dtu_peel/walk_single below are UNCHANGED and still re-verify the
        -- whole graph every pass -- a replacement edge can introduce a path
        -- through arbitrary other parts of the graph, so global
        -- cycle re-detection is not something this optimization touches.
        IF affected_con_rep IS NULL THEN
            DROP TABLE IF EXISTS _dtu_assign;
            CREATE TEMP TABLE _dtu_assign AS
            WITH cand AS MATERIALIZED (
                SELECT cm.con_rep, a.id AS opinion_id, a.containing_permid,
                       a.evidence,
                       COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) AS yr,
                       (sl.lin_rep = cm.senior_lin) AS is_senior
                FROM assignment_opinions a
                JOIN _dtu_lin sl ON sl.permid = a.subject_permid
                JOIN _dtu_con  sc ON sc.lin_rep = sl.lin_rep
                JOIN _dtu_conmeta cm ON cm.con_rep = sc.con_rep
                JOIN _dtu_linmeta lm ON lm.lin_rep = sl.lin_rep
                LEFT JOIN refs r ON r.id = a.reference_id
                LEFT JOIN _dtu_lin ccl ON ccl.permid = a.containing_permid
                LEFT JOIN _dtu_con ccc ON ccc.lin_rep = ccl.lin_rep
                LEFT JOIN _dtu_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
                WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
                  AND ( sl.lin_rep = cm.senior_lin
                        OR (cm.concept_rank_name <> 'species'
                            AND lm.accepted_rank_id = cm.concept_rank_id) )
                  AND ccc.con_rep IS DISTINCT FROM cm.con_rep
                  AND (lm.accepted_rank_height IS NULL OR ccm.accepted_rank_height IS NULL
                       OR ccm.accepted_rank_height >= lm.accepted_rank_height)
                  AND NOT EXISTS (SELECT 1 FROM _dtu_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ),
            win AS MATERIALIZED (
                SELECT con_rep, opinion_id, containing_permid, evidence, yr, is_senior,
                       row_number() OVER (PARTITION BY con_rep
                           ORDER BY evidence DESC, yr DESC NULLS LAST, opinion_id DESC) AS rn
                FROM cand
            )
            SELECT w.con_rep, w.opinion_id AS winning_assignment_opinion_id,
                   cc.con_rep AS containing_con_rep, w.evidence, w.yr, w.is_senior
            FROM win w
            LEFT JOIN _dtu_lin cl ON cl.permid = w.containing_permid
            LEFT JOIN _dtu_con cc ON cc.lin_rep = cl.lin_rep
            WHERE w.rn = 1;
            CREATE INDEX ON _dtu_assign(con_rep);
            ANALYZE _dtu_assign;

            -- ---- per-concept node (concept_permid, containing_concept_permid) --
            DROP TABLE IF EXISTS _dtu_node;
            CREATE TEMP TABLE _dtu_node AS
            SELECT cm.con_rep, cm.concept_permid, cm.concept_rank_id,
                   ccm.concept_permid AS containing_concept_permid,
                   a.winning_assignment_opinion_id, a.evidence, a.yr, a.is_senior
            FROM _dtu_conmeta cm
            LEFT JOIN _dtu_assign a ON a.con_rep = cm.con_rep
            LEFT JOIN _dtu_conmeta ccm ON ccm.con_rep = a.containing_con_rep;
            CREATE INDEX ON _dtu_node(con_rep);
            CREATE INDEX ON _dtu_node(concept_permid);
            CREATE INDEX ON _dtu_node(containing_concept_permid);
            ANALYZE _dtu_node;
        ELSE
            -- Same cand logic as the full build above, scoped to the one
            -- affected con_rep and simplified accordingly (no PARTITION BY
            -- needed once already scoped to a single con_rep).
            SELECT a.id, a.containing_permid, a.evidence,
                   COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int),
                   (sl.lin_rep = cm.senior_lin)
            INTO new_opinion_id, new_containing_permid, new_evidence, new_yr, new_is_senior
            FROM assignment_opinions a
            JOIN _dtu_lin sl ON sl.permid = a.subject_permid
            JOIN _dtu_con  sc ON sc.lin_rep = sl.lin_rep
            JOIN _dtu_conmeta cm ON cm.con_rep = sc.con_rep AND cm.con_rep = affected_con_rep
            JOIN _dtu_linmeta lm ON lm.lin_rep = sl.lin_rep
            LEFT JOIN refs r ON r.id = a.reference_id
            LEFT JOIN _dtu_lin ccl ON ccl.permid = a.containing_permid
            LEFT JOIN _dtu_con ccc ON ccc.lin_rep = ccl.lin_rep
            LEFT JOIN _dtu_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
            WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
              AND ( sl.lin_rep = cm.senior_lin
                    OR (cm.concept_rank_name <> 'species'
                        AND lm.accepted_rank_id = cm.concept_rank_id) )
              AND ccc.con_rep IS DISTINCT FROM cm.con_rep
              AND (lm.accepted_rank_height IS NULL OR ccm.accepted_rank_height IS NULL
                   OR ccm.accepted_rank_height >= lm.accepted_rank_height)
              AND NOT EXISTS (SELECT 1 FROM _dtu_excluded_opinions eo WHERE eo.opinion_id = a.id)
            ORDER BY a.evidence DESC,
                     COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                     a.id DESC
            LIMIT 1;

            IF new_opinion_id IS NOT NULL THEN
                SELECT cc.con_rep INTO new_containing_con_rep
                FROM _dtu_lin cl JOIN _dtu_con cc ON cc.lin_rep = cl.lin_rep
                WHERE cl.permid = new_containing_permid;

                UPDATE _dtu_assign SET
                    winning_assignment_opinion_id = new_opinion_id,
                    containing_con_rep = new_containing_con_rep,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;

                UPDATE _dtu_node SET
                    containing_concept_permid = (SELECT ccm.concept_permid FROM _dtu_conmeta ccm
                                                   WHERE ccm.con_rep = new_containing_con_rep),
                    winning_assignment_opinion_id = new_opinion_id,
                    evidence = new_evidence, yr = new_yr, is_senior = new_is_senior
                WHERE con_rep = affected_con_rep;
            ELSE
                DELETE FROM _dtu_assign WHERE con_rep = affected_con_rep;

                UPDATE _dtu_node SET
                    containing_concept_permid = NULL, winning_assignment_opinion_id = NULL,
                    evidence = NULL, yr = NULL, is_senior = NULL
                WHERE con_rep = affected_con_rep;
            END IF;

            new_opinion_id := NULL;
            new_containing_permid := NULL;
            new_containing_con_rep := NULL;
            new_evidence := NULL;
            new_yr := NULL;
            new_is_senior := NULL;
            affected_con_rep := NULL;
        END IF;

        -- ---- cheap survivor set via iterative peeling ----------------------
        -- Delete any node whose own parent is not itself still present,
        -- repeating to a fixed point. Survivors = cycle member(s) plus
        -- everything permanently downstream of one; empty survivors means
        -- the graph is currently acyclic.
        DROP TABLE IF EXISTS _dtu_peel;
        CREATE TEMP TABLE _dtu_peel AS
        SELECT con_rep, concept_permid, containing_concept_permid
        FROM _dtu_node WHERE containing_concept_permid IS NOT NULL;
        CREATE INDEX ON _dtu_peel(concept_permid);
        CREATE INDEX ON _dtu_peel(con_rep);
        ANALYZE _dtu_peel;

        <<peel>>
        LOOP
            DELETE FROM _dtu_peel a
            WHERE NOT EXISTS (SELECT 1 FROM _dtu_peel b WHERE b.concept_permid = a.containing_concept_permid);
            GET DIAGNOSTICS peeled_count = ROW_COUNT;
            EXIT peel WHEN peeled_count = 0;
        END LOOP peel;

        IF NOT EXISTS (SELECT 1 FROM _dtu_peel) THEN
            EXIT cycle_break;
        END IF;

        -- ---- isolate ONE genuine cycle from the (much smaller) survivor ---
        -- set: walk from an arbitrary survivor: every survivor's parent is
        -- itself a survivor (the peeling fixed-point invariant), so this
        -- walk can never exit the survivor set and is guaranteed to revisit
        -- a concept_permid. The repeated sub-path from that concept's first
        -- occurrence onward IS the cycle -- nodes visited before it are a
        -- tail leading into the cycle, not cycle members themselves.
        DROP TABLE IF EXISTS _dtu_walk_path;
        CREATE TEMP TABLE _dtu_walk_path (
            step integer PRIMARY KEY,
            con_rep uuid,
            concept_permid uuid
        );

        SELECT p.con_rep, p.concept_permid, p.containing_concept_permid
        INTO walk_con_rep, walk_concept_permid, walk_containing_permid
        FROM _dtu_peel p LIMIT 1;
        walk_step := 0;
        cycle_start_step := NULL;

        <<walk_single>>
        LOOP
            SELECT step INTO cycle_start_step FROM _dtu_walk_path WHERE concept_permid = walk_concept_permid;
            EXIT walk_single WHEN cycle_start_step IS NOT NULL;

            INSERT INTO _dtu_walk_path (step, con_rep, concept_permid)
                VALUES (walk_step, walk_con_rep, walk_concept_permid);

            SELECT p.con_rep, p.concept_permid, p.containing_concept_permid
            INTO walk_con_rep, walk_concept_permid, walk_containing_permid
            FROM _dtu_peel p WHERE p.concept_permid = walk_containing_permid;

            walk_step := walk_step + 1;
            IF walk_step > 1000000 THEN
                RAISE EXCEPTION 'derive_taxa: single-cycle walk did not converge after 1000000 steps';
            END IF;
        END LOOP walk_single;

        -- weakest winning edge among just this one cycle's members -- same
        -- tiebreak order derive_linnaean()/derive_taxa_clades() already use
        -- (see this function's header comment). Also captures which con_rep
        -- that edge belongs to (affected_con_rep) -- optimize-derive-taxa-
        -- cycle-loop's incremental recompute on the next pass needs it.
        SELECT a.winning_assignment_opinion_id, a.con_rep INTO cut_opinion_id, affected_con_rep
        FROM _dtu_walk_path wp
        JOIN _dtu_node a ON a.con_rep = wp.con_rep
        WHERE wp.step >= cycle_start_step
        ORDER BY a.evidence ASC, a.yr ASC NULLS FIRST, a.is_senior ASC, a.winning_assignment_opinion_id ASC
        LIMIT 1;

        INSERT INTO _dtu_excluded_opinions (opinion_id, concept_permid, cycle_members)
        SELECT cut_opinion_id,
               (SELECT nd.concept_permid FROM _dtu_node nd
                WHERE nd.winning_assignment_opinion_id = cut_opinion_id LIMIT 1),
               (SELECT array_agg(DISTINCT wp2.concept_permid)
                FROM _dtu_walk_path wp2 WHERE wp2.step >= cycle_start_step);
        cut_opinion_id := NULL;

        iter := iter + 1;
        IF iter > 1000 THEN
            RAISE EXCEPTION 'derive_taxa: classification cycle-breaking loop did not converge after 1000 iterations';
        END IF;
    END LOOP cycle_break;

    -- ---- classification_path (root -> node) -------------------------------
    DROP TABLE IF EXISTS _dtu_path;
    CREATE TEMP TABLE _dtu_path AS
    WITH RECURSIVE p AS (
        SELECT con_rep, concept_permid, containing_concept_permid,
               text2ltree(replace(concept_permid::text,'-','_')) AS classification_path
        FROM _dtu_node WHERE containing_concept_permid IS NULL
        UNION ALL
        SELECT cn.con_rep, cn.concept_permid, cn.containing_concept_permid,
               pp.classification_path || replace(cn.concept_permid::text,'-','_')
        FROM _dtu_node cn
        JOIN _dtu_node parent ON parent.concept_permid = cn.containing_concept_permid
        JOIN p pp ON pp.con_rep = parent.con_rep
    )
    SELECT con_rep, classification_path FROM p;
    CREATE INDEX ON _dtu_path(con_rep);
    ANALYZE _dtu_path;

    ELSE
        -- ---- seed-scoped: which con_reps the RETURN QUERY below will actually
        -- need -- computed once, up front, from the (unscoped) identity/
        -- lineage/concept union-find already built above, not re-derived per
        -- permid inside the walk.
        DROP TABLE IF EXISTS _dtu_seed_con_reps;
        CREATE TEMP TABLE _dtu_seed_con_reps AS
        SELECT DISTINCT c.con_rep
        FROM _dtu_identity m
        JOIN _dtu_lin l ON l.permid = m.permid
        JOIN _dtu_con c ON c.lin_rep = l.lin_rep
        WHERE m.permid = ANY(seed);
        CREATE INDEX ON _dtu_seed_con_reps(con_rep);
        ANALYZE _dtu_seed_con_reps;

        -- Sparse counterpart of the global _dtu_node table above -- same
        -- columns, but only ever gains a row for a con_rep actually visited
        -- by a walk below, so the RETURN QUERY at the bottom of this
        -- function needs no branching of its own between the two paths.
        DROP TABLE IF EXISTS _dtu_node;
        CREATE TEMP TABLE _dtu_node (
            con_rep uuid PRIMARY KEY,
            concept_permid uuid,
            concept_rank_id integer,
            containing_concept_permid uuid,
            winning_assignment_opinion_id bigint,
            evidence boolean,
            yr integer,
            is_senior boolean
        );
        CREATE INDEX ON _dtu_node(concept_permid);
        CREATE INDEX ON _dtu_node(containing_concept_permid);

        -- One walk per distinct con_rep the seed actually needs. A con_rep
        -- already resolved by an earlier seed's walk in this same call is
        -- skipped outright -- see design.md's correctness argument for why a
        -- cached con_rep can safely be trusted without re-walking: it was
        -- only ever cached once some walk through it fully verified
        -- everything from it to root was acyclic, and a cut can never affect
        -- a con_rep that isn't on the active walk making that cut.
        <<swalk_seed_loop>>
        FOR swalk_seed_con_rep IN SELECT con_rep FROM _dtu_seed_con_reps LOOP
            IF EXISTS (SELECT 1 FROM _dtu_node WHERE con_rep = swalk_seed_con_rep) THEN
                CONTINUE swalk_seed_loop;
            END IF;

            DROP TABLE IF EXISTS _dtu_swalk_stack;
            CREATE TEMP TABLE _dtu_swalk_stack (
                step integer PRIMARY KEY,
                con_rep uuid,
                concept_permid uuid,
                concept_rank_id integer,
                containing_concept_permid uuid,
                winning_assignment_opinion_id bigint,
                evidence boolean,
                yr integer,
                is_senior boolean
            );
            CREATE INDEX ON _dtu_swalk_stack(con_rep);

            swalk_con_rep := swalk_seed_con_rep;
            swalk_step := 0;
            swalk_iter := 0;

            -- Climb containing_concept_permid one step at a time, resolving
            -- each con_rep on demand via the same single-con_rep candidate
            -- query the seed IS NULL branch's incremental ELSE above uses,
            -- generalized to any con_rep rather than hardcoded to
            -- affected_con_rep. A revisit of a con_rep already on THIS
            -- walk's own stack is a genuine local cycle: cut its weakest
            -- edge (same tiebreak order as the global walk_single above) and
            -- restart the WHOLE walk from the seed, not from the cut point
            -- -- a cut can expose a different, larger cycle further up
            -- involving nodes not yet visited (confirmed live against the
            -- current 53-cut dataset; see design.md's Context).
            <<swalk_climb>>
            LOOP
                SELECT EXISTS (SELECT 1 FROM _dtu_node WHERE con_rep = swalk_con_rep) INTO swalk_cached;
                IF swalk_cached THEN
                    EXIT swalk_climb;
                END IF;

                SELECT step INTO swalk_cycle_start_step FROM _dtu_swalk_stack WHERE con_rep = swalk_con_rep;
                IF swalk_cycle_start_step IS NOT NULL THEN
                    SELECT s.winning_assignment_opinion_id INTO swalk_cut_opinion_id
                    FROM _dtu_swalk_stack s
                    WHERE s.step >= swalk_cycle_start_step
                    ORDER BY s.evidence ASC, s.yr ASC NULLS FIRST, s.is_senior ASC, s.winning_assignment_opinion_id ASC
                    LIMIT 1;

                    INSERT INTO _dtu_excluded_opinions (opinion_id, concept_permid, cycle_members)
                    SELECT swalk_cut_opinion_id,
                           (SELECT s2.concept_permid FROM _dtu_swalk_stack s2
                            WHERE s2.winning_assignment_opinion_id = swalk_cut_opinion_id LIMIT 1),
                           (SELECT array_agg(DISTINCT s3.concept_permid)
                            FROM _dtu_swalk_stack s3 WHERE s3.step >= swalk_cycle_start_step);

                    swalk_iter := swalk_iter + 1;
                    IF swalk_iter > 1000 THEN
                        RAISE EXCEPTION 'derive_taxa: seed-scoped cycle resolution for con_rep % did not converge after 1000 cuts',
                            swalk_seed_con_rep;
                    END IF;

                    DELETE FROM _dtu_swalk_stack;
                    swalk_con_rep := swalk_seed_con_rep;
                    swalk_step := 0;
                    CONTINUE swalk_climb;
                END IF;

                -- Same cand logic as the global build's ELSE branch above,
                -- scoped to swalk_con_rep instead of affected_con_rep.
                SELECT cm.concept_permid, cm.concept_rank_id INTO swalk_concept_permid, swalk_concept_rank_id
                FROM _dtu_conmeta cm WHERE cm.con_rep = swalk_con_rep;

                SELECT a.id, a.containing_permid, a.evidence,
                       COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int),
                       (sl.lin_rep = cm.senior_lin)
                INTO swalk_new_opinion_id, swalk_new_containing_permid, swalk_new_evidence, swalk_new_yr, swalk_new_is_senior
                FROM assignment_opinions a
                JOIN _dtu_lin sl ON sl.permid = a.subject_permid
                JOIN _dtu_con  sc ON sc.lin_rep = sl.lin_rep
                JOIN _dtu_conmeta cm ON cm.con_rep = sc.con_rep AND cm.con_rep = swalk_con_rep
                JOIN _dtu_linmeta lm ON lm.lin_rep = sl.lin_rep
                LEFT JOIN refs r ON r.id = a.reference_id
                LEFT JOIN _dtu_lin ccl ON ccl.permid = a.containing_permid
                LEFT JOIN _dtu_con ccc ON ccc.lin_rep = ccl.lin_rep
                LEFT JOIN _dtu_linmeta ccm ON ccm.lin_rep = ccl.lin_rep
                WHERE a.removed IS NOT TRUE AND a.succeeded_by_id IS NULL
                  AND ( sl.lin_rep = cm.senior_lin
                        OR (cm.concept_rank_name <> 'species'
                            AND lm.accepted_rank_id = cm.concept_rank_id) )
                  AND ccc.con_rep IS DISTINCT FROM cm.con_rep
                  AND (lm.accepted_rank_height IS NULL OR ccm.accepted_rank_height IS NULL
                       OR ccm.accepted_rank_height >= lm.accepted_rank_height)
                  AND NOT EXISTS (SELECT 1 FROM _dtu_excluded_opinions eo WHERE eo.opinion_id = a.id)
                ORDER BY a.evidence DESC,
                         COALESCE(a.publication_year, NULLIF(r.reference->>'publicationYear','')::int) DESC NULLS LAST,
                         a.id DESC
                LIMIT 1;

                IF swalk_new_opinion_id IS NOT NULL THEN
                    SELECT cc.con_rep, ccm2.concept_permid
                    INTO swalk_new_containing_con_rep, swalk_new_containing_concept_permid
                    FROM _dtu_lin cl
                    JOIN _dtu_con cc ON cc.lin_rep = cl.lin_rep
                    JOIN _dtu_conmeta ccm2 ON ccm2.con_rep = cc.con_rep
                    WHERE cl.permid = swalk_new_containing_permid;
                ELSE
                    swalk_new_containing_con_rep := NULL;
                    swalk_new_containing_concept_permid := NULL;
                END IF;

                INSERT INTO _dtu_swalk_stack (step, con_rep, concept_permid, concept_rank_id,
                    containing_concept_permid, winning_assignment_opinion_id, evidence, yr, is_senior)
                VALUES (swalk_step, swalk_con_rep, swalk_concept_permid, swalk_concept_rank_id,
                    swalk_new_containing_concept_permid, swalk_new_opinion_id, swalk_new_evidence, swalk_new_yr, swalk_new_is_senior);

                EXIT swalk_climb WHEN swalk_new_containing_concept_permid IS NULL;

                swalk_con_rep := swalk_new_containing_con_rep;
                swalk_step := swalk_step + 1;
            END LOOP swalk_climb;

            INSERT INTO _dtu_node
            SELECT con_rep, concept_permid, concept_rank_id, containing_concept_permid,
                   winning_assignment_opinion_id, evidence, yr, is_senior
            FROM _dtu_swalk_stack;
        END LOOP swalk_seed_loop;

        DROP TABLE IF EXISTS _dtu_swalk_stack;

        -- ---- classification_path, scoped to just the requested con_reps ---
        -- Bottom-up analog of the global build above: climbs containing_
        -- concept_permid pointers from each requested con_rep up through the
        -- now fully-populated (but still sparse) _dtu_node, prepending each
        -- ancestor's own label as it goes -- so the final (deepest) row per
        -- con_rep is already in root-to-node order, no separate reversal
        -- step needed.
        DROP TABLE IF EXISTS _dtu_path;
        CREATE TEMP TABLE _dtu_path AS
        WITH RECURSIVE p AS (
            SELECT sc.con_rep AS seed_con_rep, n.concept_permid AS cur_concept_permid,
                   n.containing_concept_permid AS cur_containing,
                   text2ltree(replace(n.concept_permid::text,'-','_')) AS classification_path
            FROM _dtu_seed_con_reps sc
            JOIN _dtu_node n ON n.con_rep = sc.con_rep
            UNION ALL
            SELECT p.seed_con_rep, parent.concept_permid, parent.containing_concept_permid,
                   text2ltree(replace(parent.concept_permid::text,'-','_')) || p.classification_path
            FROM p
            JOIN _dtu_node parent ON parent.concept_permid = p.cur_containing
        )
        SELECT DISTINCT ON (seed_con_rep) seed_con_rep AS con_rep, classification_path
        FROM p ORDER BY seed_con_rep, nlevel(classification_path) DESC;
        CREATE INDEX ON _dtu_path(con_rep);
        ANALYZE _dtu_path;
    END IF;

    -- ---- assemble one row per minted permid -------------------------------
    RETURN QUERY
    SELECT
        m.permid,
        m.new_name,
        m.rank_id,
        m.authority_id,
        lm.original_permid,
        lm.accepted_spelling_permid,
        cm.concept_permid,
        nd.containing_concept_permid,
        pth.classification_path,
        vv.nomenclatural_status_id,
        pe.opinion_id AS winning_name_opinion_id,
        nd.winning_assignment_opinion_id,
        vv.winning_validity_opinion_id
    FROM _dtu_identity m
    JOIN _dtu_permid_edge pe ON pe.permid = m.permid
    JOIN _dtu_lin      l   ON l.permid = m.permid
    JOIN _dtu_linmeta  lm  ON lm.lin_rep = l.lin_rep
    JOIN _dtu_con      c   ON c.lin_rep = l.lin_rep
    JOIN _dtu_conmeta  cm  ON cm.con_rep = c.con_rep
    JOIN _dtu_node     nd  ON nd.con_rep = c.con_rep
    LEFT JOIN _dtu_path pth ON pth.con_rep = c.con_rep
    LEFT JOIN _dtu_valid vv ON vv.permid = m.permid
    WHERE seed IS NULL OR m.permid = ANY(seed);
END;
$fn$;


-- ============================================================================
-- rebuild_taxa() — cold path: derive(all) → upsert into the ledger
-- ============================================================================
CREATE OR REPLACE FUNCTION rebuild_taxa()
RETURNS integer LANGUAGE plpgsql AS $fn$
DECLARE
    changed integer := 0;
    deleted integer := 0;
BEGIN
    -- Materialize derive_taxa()'s output once, so the insert/update below
    -- and the orphan deletion further down both read the same snapshot
    -- instead of calling derive_taxa(NULL) twice.
    DROP TABLE IF EXISTS _rebuild_taxa_src;
    CREATE TEMP TABLE _rebuild_taxa_src AS SELECT * FROM derive_taxa(NULL);

    -- Insert a row for every permid in the snapshot; where the permid
    -- already has a row, update it in place. The DO UPDATE ... WHERE guard makes
    -- this a true no-op (0 rows touched, per Postgres's own ON CONFLICT row-count
    -- semantics) when nothing has actually changed.
    INSERT INTO taxa (permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        classification_path, nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id)
    SELECT permid, name, rank_id, authority_id, original_permid,
        accepted_spelling_permid, concept_permid, containing_concept_permid,
        classification_path, nomenclatural_status_id, winning_name_opinion_id,
        winning_assignment_opinion_id, winning_validity_opinion_id
    FROM _rebuild_taxa_src
    ON CONFLICT (permid) DO UPDATE SET
        name                          = EXCLUDED.name,
        rank_id                       = EXCLUDED.rank_id,
        authority_id                  = EXCLUDED.authority_id,
        original_permid               = EXCLUDED.original_permid,
        accepted_spelling_permid      = EXCLUDED.accepted_spelling_permid,
        concept_permid                = EXCLUDED.concept_permid,
        containing_concept_permid     = EXCLUDED.containing_concept_permid,
        classification_path           = EXCLUDED.classification_path,
        nomenclatural_status_id       = EXCLUDED.nomenclatural_status_id,
        winning_name_opinion_id       = EXCLUDED.winning_name_opinion_id,
        winning_assignment_opinion_id = EXCLUDED.winning_assignment_opinion_id,
        winning_validity_opinion_id   = EXCLUDED.winning_validity_opinion_id
    WHERE taxa.name                      IS DISTINCT FROM EXCLUDED.name
       OR taxa.rank_id                   IS DISTINCT FROM EXCLUDED.rank_id
       OR taxa.authority_id              IS DISTINCT FROM EXCLUDED.authority_id
       OR taxa.original_permid           IS DISTINCT FROM EXCLUDED.original_permid
       OR taxa.accepted_spelling_permid  IS DISTINCT FROM EXCLUDED.accepted_spelling_permid
       OR taxa.concept_permid            IS DISTINCT FROM EXCLUDED.concept_permid
       OR taxa.containing_concept_permid IS DISTINCT FROM EXCLUDED.containing_concept_permid
       OR taxa.classification_path       IS DISTINCT FROM EXCLUDED.classification_path
       OR taxa.nomenclatural_status_id   IS DISTINCT FROM EXCLUDED.nomenclatural_status_id
       OR taxa.winning_name_opinion_id       IS DISTINCT FROM EXCLUDED.winning_name_opinion_id
       OR taxa.winning_assignment_opinion_id IS DISTINCT FROM EXCLUDED.winning_assignment_opinion_id
       OR taxa.winning_validity_opinion_id   IS DISTINCT FROM EXCLUDED.winning_validity_opinion_id;
    GET DIAGNOSTICS changed = ROW_COUNT;

    -- Remove rows for permids no longer produced by derive_taxa() -- e.g. a
    -- lineage that lost its last remaining candidate. The upsert above has
    -- no way to detect or handle this: ON CONFLICT only ever inserts/updates.
    DELETE FROM taxa t
    WHERE NOT EXISTS (SELECT 1 FROM _rebuild_taxa_src s WHERE s.permid = t.permid);
    GET DIAGNOSTICS deleted = ROW_COUNT;
    changed := changed + deleted;

    -- Snapshot this run's cuts (left behind in _dtu_excluded_opinions by the
    -- derive_taxa() call above, in this same session) into the permanent log.
    DELETE FROM cycle_cuts WHERE source = 'taxa';
    INSERT INTO cycle_cuts (source, concept_permid, cut_opinion_id, cycle_members)
    SELECT 'taxa', concept_permid, opinion_id, cycle_members FROM _dtu_excluded_opinions;

    RETURN changed;
END;
$fn$;


-- ============================================================================
-- assert_taxa_invariant() — derive(all) ≡ the current taxa rows
-- ============================================================================
CREATE OR REPLACE FUNCTION assert_taxa_invariant()
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
    bad integer;
BEGIN
    WITH d AS (SELECT * FROM derive_taxa(NULL)),
    heads AS (SELECT * FROM taxa),
    mism AS (
        SELECT COALESCE(d.permid, h.permid) AS permid FROM d
        FULL JOIN heads h ON h.permid = d.permid
        WHERE d.permid IS NULL OR h.permid IS NULL
           OR h.name IS DISTINCT FROM d.name
           OR h.rank_id IS DISTINCT FROM d.rank_id
           OR h.original_permid IS DISTINCT FROM d.original_permid
           OR h.accepted_spelling_permid IS DISTINCT FROM d.accepted_spelling_permid
           OR h.concept_permid IS DISTINCT FROM d.concept_permid
           OR h.containing_concept_permid IS DISTINCT FROM d.containing_concept_permid
           OR h.classification_path IS DISTINCT FROM d.classification_path
           OR h.nomenclatural_status_id IS DISTINCT FROM d.nomenclatural_status_id
    )
    SELECT count(*) INTO bad FROM mism;
    IF bad > 0 THEN
        RAISE EXCEPTION 'assert_taxa_invariant: % permid(s) diverge between derive_taxa(all) and the current taxa rows', bad;
    END IF;
END;
$fn$;


-- ============================================================================
-- rebuild_taxa_full() — the supported entry point for a full rebuild across
-- all four ledgers
-- ============================================================================
-- Enforces correct ordering: rebuild_linnaean() must run before
-- rebuild_taxa_clades() (which reads taxa_linnaean's lineage-level output),
-- which must run before rebuild_clade_attachments() (which reads both
-- taxa_linnaean's and taxa_clades's resolved concept output). rebuild_taxa()
-- (the primary, combined derivation) runs last; it re-derives from the raw
-- opinion tables directly rather than reading the other three, so it has no
-- ordering dependency on them, but running it last keeps its cycle_cuts rows
-- easiest to diff against the other three's during validation. No
-- transaction-control statements needed: a plain PL/pgSQL function already
-- runs as part of its caller's transaction -- calling all four steps in
-- sequence inside one function body already gives the required atomicity.
--
-- ANALYZE between stages is included from the start, not added reactively: a
-- sibling exploration of a different storage design for this same problem
-- (branch clade-rework-single, openspec/changes/extend-taxa-for-clades) hit a
-- real 9+ minute incident here, caused by a bulk write leaving the next
-- stage's heavy self-joins planning off stale post-truncate statistics -- the
-- same class of bug as this project's own derive-taxa-performance-fix.
-- ANALYZE taxa_linnaean after rebuild_linnaean() and ANALYZE taxa_clades after
-- rebuild_taxa_clades() pre-empt the same failure here. No trailing ANALYZE
-- for taxa_attachments or taxa -- nothing downstream reads either within this
-- function.
CREATE OR REPLACE FUNCTION rebuild_taxa_full()
RETURNS TABLE (
    taxa_linnaean_changed integer,
    taxa_clades_changed integer,
    taxa_attachments_changed integer,
    taxa_changed integer
) LANGUAGE plpgsql AS $fn$
BEGIN
    taxa_linnaean_changed := rebuild_linnaean();
    EXECUTE 'ANALYZE taxa_linnaean';
    taxa_clades_changed := rebuild_taxa_clades();
    EXECUTE 'ANALYZE taxa_clades';
    taxa_attachments_changed := rebuild_clade_attachments();
    taxa_changed := rebuild_taxa();
    RETURN NEXT;
END;
$fn$;
